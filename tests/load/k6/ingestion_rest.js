// E08-Q04 scenario 4: ingestion REST read profile (budget #13 p95 < 150 ms; cold vs warm klines).
// Target is ONLY the local fixture app started by `python -m bench.ingestion.runner rest_k6
// --profile full` (127.0.0.1, recorded-fixture backend; never an exchange host, C-13.5), and the
// second app it starts for the first-read leg (#2523):
//   k6 run -e BASE_URL=http://127.0.0.1:<port> -e BASE_URL_FIRST=http://127.0.0.1:<port2> \
//     -e PLAN=plan.json tests/load/k6/ingestion_rest.js
// Set VUS and DURATION with -e only: k6's own --vus and --duration (or K6_VUS and K6_DURATION)
// would replace both scenarios with one that runs the default export, which this script lacks.
// The request plan (paths + params) is generated by `bench/ingestion/fixture_app.requests_plan`
// so k6 and the in-process PR smoke hit exactly the same requests. A route it marks `first_read`
// (`klines_cold_first`) goes to BASE_URL_FIRST, whose reader no other route reads through, in a
// scenario of its own, so the 5 VUs send the 7-route mix recorded before it (#2523); its p95 is
// reported, never gated. No credentials are used.
/* global __ENV, open -- k6 init-context globals */
import http from "k6/http";
import { check, fail } from "k6";
import { Trend } from "k6/metrics";

const LOOPBACK = /^http:\/\/(127\.0\.0\.1|localhost)(:\d+)?$/;
const BASE = __ENV.BASE_URL || "http://127.0.0.1:8000";
if (!LOOPBACK.test(BASE)) {
  fail(`refusing non-loopback target ${BASE}`); // security notes: bench is pinned to the stub
}
const BASE_FIRST = __ENV.BASE_URL_FIRST || "";
if (!LOOPBACK.test(BASE_FIRST)) {
  fail(`refusing first-read target ${BASE_FIRST || "(BASE_URL_FIRST unset)"}: not loopback`);
}
const PLAN = JSON.parse(open(__ENV.PLAN));
const ROUTES = Object.keys(PLAN);
const GATED = ROUTES.filter((r) => !PLAN[r].first_read); // a first read has no budget (#2523)
const FIRST = ROUTES.filter((r) => PLAN[r].first_read); // sent by `first_read` alone
const trends = {};
for (const r of ROUTES) trends[r] = new Trend(`route_${r}_ms`, true);

const thresholds = { checks: ["rate>0.99"] };
for (const r of GATED) thresholds[`route_${r}_ms`] = ["p(95)<150"]; // budget #13 (reads)

const DURATION = __ENV.DURATION || "60s";
// The first-read leg's own load (#2523): an arrival rate, so its latency sets neither that load
// nor the 5 VUs' pace, and a modest one, 1 a second, so each first read finds its reader idle
// while a cold read takes under a second.
const FIRST_READ_RATE = 1;

export const options = {
  scenarios: {
    // 5 concurrent users = the §9 "realistic-peak" REST load, on the 7 budget routes.
    reads: {
      executor: "constant-vus",
      exec: "reads",
      vus: Number(__ENV.VUS || 5),
      duration: DURATION,
    },
    // 2 VUs keep the rate while one first read runs past a second.
    first_read: {
      executor: "constant-arrival-rate",
      exec: "firstRead",
      rate: FIRST_READ_RATE,
      timeUnit: "1s",
      duration: DURATION,
      preAllocatedVUs: 2,
    },
  },
  thresholds,
  summaryTrendStats: ["p(50)", "p(95)", "max", "count"],
};

function qs(params) {
  return Object.keys(params)
    .map((k) => `${encodeURIComponent(k)}=${encodeURIComponent(params[k])}`)
    .join("&");
}

function get(r, base) {
  const spec = PLAN[r];
  const res = http.get(`${base}${spec.path}?${qs(spec.params)}`, { tags: { route: r } });
  trends[r].add(res.timings.duration);
  check(res, { [`${r} 200`]: (x) => x.status === 200 });
}

export function reads() {
  for (const r of GATED) get(r, BASE);
}

export function firstRead() {
  for (const r of FIRST) get(r, BASE_FIRST);
}
