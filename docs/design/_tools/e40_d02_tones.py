#!/usr/bin/env python3
"""E40-D02: generate the four alert tones and their manifest from the spec's §9.2 recipe.

Stdlib only (``struct``, ``math``, ``hashlib``, ``json``), offline, deterministic. Writes
``docs/design/E40/sounds/{alert,urgent,reject,critical}-tone.wav`` and ``manifest.json`` (each
file's label, default use, length, sample rate, bytes and sha256). Provenance: generated by
``e40_d02_tones.py`` from §9.2's recipe; no third-party audio. §9.3 (RULED Q7) names ``wave``
among the modules; ``struct`` writes the RIFF header in its place, the same stdlib-only bytes.

The recipe (``docs/design/E40/E40-D02.md`` §9.2): PCM WAV, mono, 16-bit signed little-endian,
22,050 Hz, a canonical 44-byte RIFF header and no other chunk. A segment of ``ms`` milliseconds
has ``22050 * ms // 1000`` samples; a note at ``f`` Hz is ``sin(2*pi*f*t) + 0.2*sin(4*pi*f*t)``
shaped by a 5 ms linear onset, an exponential decay ``exp(-t/tau)`` and a 10 ms linear release to
zero at its end; a gap is silence. Each tone is scaled so its peak is 0.708 of full scale
(-3 dBFS) and rounded to the nearest integer.

Usage: python3 -I -B docs/design/_tools/e40_d02_tones.py [--check] [--json]
  (no flag)  write the four WAVs and manifest.json
  --check    regenerate in memory and fail (exit 1) on any byte difference, or on a budget miss
  --json     print the manifest
The budget (14 SCR-115 Performance; RULED Q7): the four files total at most 200 KB (204,800
bytes), each at most 100 KB (102,400 bytes); both are asserted on every run.
"""

from __future__ import annotations

import hashlib
import json
import math
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "docs/design/E40/sounds"
RATE = 22050
FULL_SCALE = 32767
PEAK = 0.708
ONSET_S, RELEASE_S = 0.005, 0.010
TOTAL_BUDGET, FILE_BUDGET = 200 * 1024, 100 * 1024
PROVENANCE = "generated by `e40_d02_tones.py` from §9.2's recipe; no third-party audio"

# (file stem, label, default use, segments as (Hz or None for a gap, ms), tau in ms) — §9.1, §9.2
TONES: tuple[tuple[str, str, str, tuple[tuple[float | None, int], ...], float], ...] = (
    (
        "alert-tone",
        "Alert tone",
        "alerts of severity Info and Warning",
        ((880.00, 110), (None, 30), (1318.51, 170)),
        60.0,
    ),
    (
        "urgent-tone",
        "Urgent tone",
        "alerts of severity Error and Critical; the risk warning band (K7)",
        ((987.77, 90), (None, 40), (987.77, 90), (None, 40), (1318.51, 160)),
        50.0,
    ),
    (
        "reject-tone",
        "Reject tone",
        "ordinary order rejects (K6a)",
        ((659.26, 120), (None, 30), (440.00, 200)),
        80.0,
    ),
    (
        "critical-tone",
        "Critical tone",
        "every locked override kind (CO-1..CO-12)",
        (
            (783.99, 100),
            (None, 30),
            (1046.50, 100),
            (None, 30),
            (783.99, 100),
            (None, 30),
            (1046.50, 100),
            (None, 30),
            (1567.98, 220),
        ),
        70.0,
    ),
)


def segment(freq: float | None, ms: int, tau_ms: float) -> list[float]:
    """One note or gap, unscaled."""
    n = RATE * ms // 1000
    if freq is None:
        return [0.0] * n
    dur = n / RATE
    tau = tau_ms / 1000.0
    out: list[float] = []
    for i in range(n):
        t = i / RATE
        wave = math.sin(2 * math.pi * freq * t) + 0.2 * math.sin(4 * math.pi * freq * t)
        onset = min(1.0, t / ONSET_S)
        release = max(0.0, min(1.0, (dur - t) / RELEASE_S))
        out.append(wave * onset * math.exp(-t / tau) * release)
    return out


def render(segments: tuple[tuple[float | None, int], ...], tau_ms: float) -> bytes:
    """The whole WAV file: a canonical 44-byte header, then 16-bit little-endian samples."""
    raw: list[float] = []
    for freq, ms in segments:
        raw += segment(freq, ms, tau_ms)
    peak = max(abs(v) for v in raw)
    scale = PEAK * FULL_SCALE / peak
    pcm = struct.pack(f"<{len(raw)}h", *(round(v * scale) for v in raw))
    header = struct.pack(
        "<4sI4s4sIHHIIHH4sI",
        b"RIFF",
        36 + len(pcm),
        b"WAVE",
        b"fmt ",
        16,  # PCM fmt chunk size
        1,  # PCM
        1,  # mono
        RATE,
        RATE * 2,  # byte rate
        2,  # block align
        16,  # bits per sample
        b"data",
        len(pcm),
    )
    return header + pcm


def build() -> dict[str, bytes]:
    """Every output file name -> its exact bytes (the WAVs, then manifest.json)."""
    files: dict[str, bytes] = {}
    entries: dict[str, dict[str, object]] = {}
    for stem, label, use, segments, tau in TONES:
        data = render(segments, tau)
        name = f"{stem}.wav"
        files[name] = data
        entries[name] = {
            "label": label,
            "default_use": use,
            "length_ms": sum(ms for _, ms in segments),
            "sample_rate_hz": RATE,
            "bytes": len(data),
            "sha256": hashlib.sha256(data).hexdigest(),
        }
    manifest = {
        "provenance": PROVENANCE,
        "recipe": "docs/design/E40/E40-D02.md §9.2",
        "budget_bytes": {"total": TOTAL_BUDGET, "each": FILE_BUDGET},
        "total_bytes": sum(len(b) for b in files.values()),
        "files": entries,
    }
    files["manifest.json"] = (json.dumps(manifest, ensure_ascii=False, indent=2) + "\n").encode()
    return files


def budget_problems(files: dict[str, bytes]) -> list[str]:
    wavs = {n: b for n, b in files.items() if n.endswith(".wav")}
    bad = [f"{n}: {len(b)} bytes > {FILE_BUDGET}" for n, b in wavs.items() if len(b) > FILE_BUDGET]
    total = sum(len(b) for b in wavs.values())
    if total > TOTAL_BUDGET:
        bad.append(f"total {total} bytes > {TOTAL_BUDGET}")
    if len(wavs) != 4:
        bad.append(f"{len(wavs)} tones, the set is four")
    return bad


def check(files: dict[str, bytes]) -> list[str]:
    bad = budget_problems(files)
    for name, data in files.items():
        path = OUT / name
        if not path.is_file():
            bad.append(f"{name}: missing on disk")
        elif path.read_bytes() != data:
            bad.append(f"{name}: differs from the regenerated bytes")
    extra = sorted(p.name for p in OUT.glob("*") if p.name not in files) if OUT.is_dir() else []
    bad += [f"{name}: on disk but not generated" for name in extra]
    return bad


def main(argv: list[str]) -> int:
    unknown = [a for a in argv if a not in ("--check", "--json")]
    if unknown:
        print(
            f"usage: e40_d02_tones.py [--check] [--json]; unknown argument(s): {' '.join(unknown)}"
        )
        return 2
    files = build()
    if "--json" in argv:
        print(files["manifest.json"].decode(), end="")
    if "--check" in argv:
        bad = check(files)
        for b in bad:
            print(f"FAIL {b}")
        if not bad:
            total = sum(len(b) for n, b in files.items() if n.endswith(".wav"))
            print(f"--check: ok — 4 tones, {total} bytes, byte-identical to the recipe")
        return 1 if bad else 0
    bad = budget_problems(files)
    if bad:
        for b in bad:
            print(f"FAIL {b}")
        return 1
    if "--json" not in argv:
        OUT.mkdir(parents=True, exist_ok=True)
        for name, data in files.items():
            (OUT / name).write_bytes(data)
        print(f"wrote {len(files)} files to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
