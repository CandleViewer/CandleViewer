#!/usr/bin/env python3
"""E05-D04 CVD review of the shipped v0 tokens, 3 themes x 3 deficiencies.

Reads the real token files (layered as packages/ui/tokens/tests/verify_tokens.py layers them) and
measures the semantic pairs that carry meaning with the E05-D07 method: simulate() from
docs/research/_tools/cvd_simulate.py (Brettel/Vienot protan and deutan, Machado tritan) and CIE76 dE
against its JND floor (5.0). Deterministic, no network.

Usage (repo root): python3 docs/design/_tools/cvd_v0_report.py > docs/research/artifacts/E05-D04/cvd_simulation_v0.md
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]


def _load(name: str, rel: str):
    spec = importlib.util.spec_from_file_location(name, ROOT / rel)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


vt = _load("verify_tokens", "packages/ui/tokens/tests/verify_tokens.py")
cs = _load("cvd_simulate", "docs/research/_tools/cvd_simulate.py")
FLOOR = cs.JND_FLOOR
DEFS = ("deuteranopia", "protanopia", "tritanopia")
THEMES = ("dark", "light", "high-contrast")


def colours(theme: str) -> dict[str, str]:
    prim = vt.load(vt.PRIMITIVES)
    merged = vt.merged_set(vt.THEMES[theme])
    allt = {**prim, **merged}
    return {
        k: vt.resolve(v["$value"], allt)
        for k, v in merged.items()
        if str(vt.resolve(v["$value"], allt)).startswith("#")
    }


def pairs(c: dict[str, str]) -> list[tuple[str, str, str, str]]:
    """(group, label, token a, token b)."""
    out: list[tuple[str, str, str, str]] = []
    add = lambda g, a, b: out.append(
        (g, f"{a.removeprefix('color.')} / {b.removeprefix('color.')}", a, b)
    )
    add("buy/sell", "color.buy.default", "color.sell.default")
    add("buy/sell", "color.buy.hc", "color.sell.hc")
    add("buy/sell", "color.candle.up", "color.candle.down")
    add("buy/sell", "color.cvd.buy", "color.cvd.sell")
    s = ["success", "warning", "danger", "info"]
    for i, a in enumerate(s):
        for b in s[i + 1 :]:
            add("status", f"color.status.{a}.default", f"color.status.{b}.default")
    for a in s:
        add(
            "status (strong vs subtle)",
            f"color.status.{a}.strong",
            f"color.status.{a}.subtle",
        )
    add("focus ring", "color.focus.ring", "color.surface.app")
    add("focus ring", "color.focus.ring", "color.surface.raised")
    add("focus ring", "color.focus.ring", "color.surface.selected")
    add(
        "PreviewTile warning glyph",
        "color.status.warning.strong",
        "color.surface.sunken",
    )
    add(
        "PreviewTile warning glyph",
        "color.status.warning.strong",
        "color.status.danger.strong",
    )
    add("chart ink", "color.candle.up", "color.surface.canvas")
    add("chart ink", "color.candle.down", "color.surface.canvas")
    add("chart ink", "color.candle.wick", "color.surface.canvas")
    add("chart ink", "color.cvd.imbalance", "color.surface.canvas")
    for ramp in ("heatmap", "cvd.heatmap"):
        add(f"{ramp} bid vs ask", f"color.{ramp}.bid.5", f"color.{ramp}.ask.5")
        add(f"{ramp} bid vs ask", f"color.{ramp}.bid.1", f"color.{ramp}.ask.1")
    return [p for p in out if p[2] in c and p[3] in c]


def main() -> None:
    L: list[str] = []
    L += [
        "# E05-D04: CVD simulation of the shipped v0 tokens (generated)",
        "",
        (
            "Generated by `docs/design/_tools/cvd_v0_report.py` (run from the repo root); do not edit by hand. Colours are the "
            "resolved tokens of each theme as `packages/ui/tokens/tests/verify_tokens.py` layers them. Method is E05-D07's, "
            "imported from `docs/research/_tools/cvd_simulate.py`: protan and deutan run sRGB, linear, LMS, back "
            "(Brettel/Vienot); tritan runs Machado on linear RGB; CIE76 dE is computed from the encoded hex values; "
            f"JND floor {FLOOR:.1f}. A pair below the floor is FLAG; a FLAG on a pair that is a "
            "meaning-carrying pair is a finding, reviewed in `E05-D04-a11y-cvd-signoff.md` §3."
        ),
        "",
    ]
    flags: list[str] = []
    for theme in THEMES:
        c = colours(theme)
        L += [
            f"## Theme: {theme}",
            "",
            "| Group | Pair (a / b) | Hex a / b | dE normal | "
            + " | ".join(f"dE {d[:5]}." for d in DEFS)
            + " | Min | Verdict |",
            "|---|---|---|---|---|---|---|---|---|",
        ]
        for g, label, a, b in pairs(c):
            des = [cs.delta_e76(cs.simulate(c[a], d), cs.simulate(c[b], d)) for d in DEFS]
            m = min(des)
            v = "ok" if m >= FLOOR else "FLAG"
            if v == "FLAG":
                flags.append(f"{theme}: {g}: {label} (min dE {m:.1f}, {DEFS[des.index(m)]})")
            L.append(
                f"| {g} | {label} | {c[a]} / {c[b]} | {cs.delta_e76(c[a], c[b]):.1f} | "
                + " | ".join(f"{x:.1f}" for x in des)
                + f" | {m:.1f} | {v} |"
            )
        L.append("")
        L += [
            f"### {theme}: adjacent heatmap ramp stops",
            "",
            "| Ramp | Side | Stops | dE normal | "
            + " | ".join(f"dE {d[:5]}." for d in DEFS)
            + " | Min | Verdict |",
            "|---|---|---|---|---|---|---|---|---|",
        ]
        for ramp in ("heatmap", "cvd.heatmap"):
            for side in ("bid", "ask"):
                stops = [f"color.{ramp}.{side}.{i}" for i in range(1, 6)]
                if not all(s in c for s in stops):
                    continue
                for i in range(4):
                    des = [
                        cs.delta_e76(cs.simulate(c[stops[i]], d), cs.simulate(c[stops[i + 1]], d))
                        for d in DEFS
                    ]
                    m = min(des)
                    v = "ok" if m >= FLOOR else "FLAG"
                    if v == "FLAG":
                        flags.append(
                            f"{theme}: {ramp} {side} stops {i + 1}-{i + 2} (min dE {m:.1f}, {DEFS[des.index(m)]})"
                        )
                    L.append(
                        f"| {ramp} | {side} | {i + 1}-{i + 2} | {cs.delta_e76(c[stops[i]], c[stops[i + 1]]):.1f} | "
                        + " | ".join(f"{x:.1f}" for x in des)
                        + f" | {m:.1f} | {v} |"
                    )
        L.append("")
    L += (
        [f"## Flags ({len(flags)})", ""]
        + ([f"- {f}" for f in flags] if flags else ["- none"])
        + [""]
    )
    print("\n".join(L))


if __name__ == "__main__":
    main()
