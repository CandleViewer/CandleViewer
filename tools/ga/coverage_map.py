#!/usr/bin/env python3
"""E49-Q01 (#1335, BQ-10): the GA regression pack's coverage map, Must stories to pack scenarios.

The map is generated from the specs' tags (specs.py), so it cannot drift from them: a Must story
of docs/plan/11-user-stories.md is **covered** when at least one runnable pack test (not a
``test.fixme`` stub) carries ``@story-<id>``, and is otherwise a **gap** that
``docs/qa/ga-coverage-gaps.json`` must declare with its owning epic, its ``surface`` (why it is a
gap, checked against the code by surfaces.py; the map's reason is rendered from it, never typed)
and a risk acceptance reference (Gherkin "The pack covers every Must story or names the gap"). A
gap may name the ``test.fixme`` stub that un-fixmes with its surface (BQ-01).

A risk acceptance is the owner's to give: a ``PROPOSED`` reference is reported as **pending owner
acceptance** in the map and by health.py (a warning; ``--require-accepted`` makes it a finding),
never as a passing gap.

``check`` (run by health.py, so by the nightly) fails on: a Must story neither covered nor
declared; a declared gap for a story that is covered (stale) or is not a Must story; a gap without
its fields; a surface the code contradicts (surfaces.py); a named stub that holds no fixme pack
test for its story; and a committed map
(``docs/qa/ga-coverage-map.md``) that differs from a fresh render.

    python3 tools/ga/coverage_map.py --write   # regenerate docs/qa/ga-coverage-map.md

Stdlib only.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from collections.abc import Sequence
from pathlib import Path
from typing import Any

if __package__ in (None, ""):  # run as a script
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from tools.ga import specs, surfaces

GAPS = "docs/qa/ga-coverage-gaps.json"
MAP = "docs/qa/ga-coverage-map.md"
GAP_FIELDS = ("story", "owner_epic", "surface", "risk_acceptance_ref")
PROPOSED = "PROPOSED"


def load_gaps(root: Path) -> list[dict[str, Any]]:
    data = json.loads((root / GAPS).read_text(encoding="utf-8"))
    gaps = data.get("gaps")
    if not isinstance(gaps, list):
        raise ValueError(f"{GAPS}: `gaps` must be a list")
    return gaps


def is_pending(gap: dict[str, Any]) -> bool:
    return str(gap.get("risk_acceptance_ref", "")).startswith(PROPOSED)


def pending(root: Path) -> list[str]:
    """Stories whose gap still awaits the owner's risk acceptance."""
    try:
        return [str(g.get("story")) for g in load_gaps(root) if is_pending(g)]
    except (OSError, ValueError):
        return []


def covering(tests: Sequence[specs.SpecTest]) -> dict[str, list[specs.SpecTest]]:
    out: dict[str, list[specs.SpecTest]] = defaultdict(list)
    for t in tests:
        if t.in_pack and not t.stub:
            for s in t.stories:
                out[s].append(t)
    return out


def render(root: Path, tests: Sequence[specs.SpecTest], gaps: Sequence[dict[str, Any]]) -> str:
    must = specs.must_stories(root)
    cover = covering(tests)
    by_story = {g.get("story"): g for g in gaps}
    covered = [s for s in must if s in cover]
    code = surfaces.Code(root)
    waiting = sum(1 for s in must if s not in cover and is_pending(by_story.get(s, {})))
    lines = [
        "<!-- Generated by tools/ga/coverage_map.py --write; do not edit (E49-Q01, #1335). -->",
        "",
        "# GA regression pack: coverage map (Must stories)",
        "",
        f"Must stories: {len(must)}. Covered by a runnable pack scenario: {len(covered)}."
        f" Declared gaps: {len(must) - len(covered)} (`{GAPS}`), of which"
        f" {waiting} are **pending owner acceptance** and {len(must) - len(covered) - waiting}"
        " accepted.",
        "",
        "A story is covered when a runnable `@ga-regression` test carries `@story-<id>`; a",
        "`test.fixme` stub covers nothing. Each gap's reason is rendered from its `surface`, which",
        "`tools/ga/surfaces.py` checks against the code (screens from 18-traceability-matrix.md,",
        "route stubs from routes/tree.tsx, mounted files from the app entry points). A `PROPOSED`",
        "risk acceptance is not an acceptance: the gap is pending until the owner accepts it.",
        "",
        "| Story | Title | Status | Pack scenarios (file: tests) or gap | Owner epic |",
        "|---|---|---|---|---|",
    ]
    for story, title in must.items():
        if story in cover:
            per_file: dict[str, int] = defaultdict(int)
            for t in cover[story]:
                per_file[t.path] += 1
            where = "<br>".join(f"`{p}`: {n}" for p, n in sorted(per_file.items()))
            lines.append(f"| {story} | {title} | covered | {where} | |")
        else:
            g = by_story.get(story, {})
            reason = surfaces.reason(g, code) if g else "UNDECLARED"
            stub = f" (stub `{g['stub']}`)" if g.get("stub") else ""
            state = "gap, pending owner acceptance" if is_pending(g) else "gap"
            lines.append(
                f"| {story} | {title} | {state} | {reason}{stub};"
                f" risk acceptance: {g.get('risk_acceptance_ref', 'none')} |"
                f" {g.get('owner_epic', '')} |"
            )
    return "\n".join(lines) + "\n"


def check(root: Path, tests: Sequence[specs.SpecTest] | None = None) -> list[str]:
    tests = specs.scan(root) if tests is None else tests
    must = specs.must_stories(root)
    cover = covering(tests)
    try:
        gaps = load_gaps(root)
    except (OSError, ValueError) as exc:
        return [f"{GAPS}: unreadable ({exc})"]
    out = []
    seen: set[str] = set()
    for g in gaps:
        story = str(g.get("story", ""))
        missing = [f for f in GAP_FIELDS if not str(g.get(f, "")).strip()]
        if missing:
            out.append(f"{GAPS}: gap {story or '?'} lacks {', '.join(missing)}")
        if story in seen:
            out.append(f"{GAPS}: {story} is declared twice")
        seen.add(story)
        if story not in must:
            out.append(f"{GAPS}: {story} is not a Must story in 11-user-stories.md")
        elif story in cover:
            out.append(f"{GAPS}: {story} is covered by the pack; delete its gap entry")
        stub = g.get("stub")
        if stub and not any(
            t.path == stub and t.stub and t.in_pack and story in t.stories for t in tests
        ):
            out.append(f"{GAPS}: {story} names stub {stub}, which has no fixme pack test for it")
    out += surfaces.check_all(
        [g for g in gaps if str(g.get("story")) in must and str(g.get("story")) not in cover], root
    )
    for story in must:
        if story not in cover and story not in seen:
            out.append(f"{story}: Must story neither covered by the pack nor a declared gap")
    path = root / MAP
    if not path.exists() or path.read_text(encoding="utf-8") != render(root, tests, gaps):
        out.append(f"{MAP} is stale: run python3 tools/ga/coverage_map.py --write")
    return out


def main(argv: Sequence[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    p.add_argument("--root", type=Path, default=specs.REPO_ROOT)
    p.add_argument("--write", action="store_true", help=f"regenerate {MAP}")
    args = p.parse_args(argv)
    if args.write:
        tests = specs.scan(args.root)
        (args.root / MAP).write_text(
            render(args.root, tests, load_gaps(args.root)), encoding="utf-8"
        )
    findings = check(args.root)
    for f in findings:
        print(f"::error title=ga-regression coverage::{f}")
    return 1 if findings else 0


if __name__ == "__main__":
    sys.exit(main())
