// E15-K01 (#371) mirror cases: this test reads the throwaway spike harness
// (`docs/plan/spikes/E15-K01-harness/lib.mjs`) and its stored windows to check that the app's probe and
// trigger agree with what the spike measured. The dependency runs one way (the harness imports nothing
// from the app). When the harness is deleted, delete the mirror cases here with it; E15-S08 (#561), which
// owns the probe's calibration on reference hardware, decides when.
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { describe, expect, it } from "vitest";
import {
  classify,
  frameSpanMs,
  reducedTrigger,
  type FrameWindow,
  type TimedFrame,
} from "../../../src/lib/capability/frameProbe";

// #371 AC2: the app's rules on frame times measured by the E15-K01 harness (one 120-frame window at one pane
// and one at four, per leg). The harness mirrors the rules (it imports nothing from the app). Two checks, so
// the app and the mirror cannot drift silently: the fixture carries the answers the mirror wrote during the run
// (generated by `docs/plan/spikes/E15-K01-harness/run.mjs`; never hand-edited), and this test loads the mirror
// (`lib.mjs`, plain JS with no imports) to run its `classify` and `reducedTrigger` beside the app's.
interface Run {
  readonly leg: string;
  readonly windows: readonly FrameWindow[];
  readonly expected: {
    readonly recommendedMaxPanes: number;
    readonly recommendedProfile: string;
    readonly p95FrameMs: number;
  };
}
const fixture = JSON.parse(
  readFileSync(resolve(import.meta.dirname, "fixtures/e15-k01-windows.json"), "utf8"),
) as { readonly runs: readonly Run[] };

interface MirrorTrigger {
  readonly fired: boolean;
  readonly p95: number | null;
  readonly frames: number;
}
interface Mirror {
  readonly classify: (windows: readonly FrameWindow[]) => {
    readonly recommendedMaxPanes: number;
    readonly recommendedProfile: string;
    readonly p95FrameMs: number;
    readonly paneCount: number;
  };
  readonly reducedTrigger: (
    samples: readonly { readonly t: number; readonly ms: number }[],
    options?: { readonly outliers?: "all" | "isolated" },
  ) => MirrorTrigger;
}
const LIB = resolve(import.meta.dirname, "../../../../../docs/plan/spikes/E15-K01-harness/lib.mjs");
const mirror = (await import(pathToFileURL(LIB).href)) as Mirror;

// a measured window laid end to end on a timeline long enough for the trigger (10 s warm-up + 60 s window)
function timeline(frameMs: readonly number[], seconds = 71): TimedFrame[] {
  const out: TimedFrame[] = [];
  for (let t = 0, i = 0; t < seconds * 1000; i += 1) {
    const ms = frameMs[i % frameMs.length] ?? 0;
    out.push({ atMs: t, frameMs: ms });
    t += frameSpanMs(ms);
  }
  return out;
}
const asSamples = (frames: readonly TimedFrame[]) =>
  frames.map((f) => ({ t: f.atMs, ms: f.frameMs }));
const sameTrigger = (frames: readonly TimedFrame[], outliers: "all" | "isolated" = "isolated") => {
  const app = reducedTrigger(frames);
  const mir = mirror.reducedTrigger(asSamples(frames), { outliers });
  return { app, mir };
};

describe("classify on the E15-K01 measured windows", () => {
  it("e15k01_fixture_has_the_three_legs", () => {
    expect(fixture.runs.map((r) => r.leg).sort()).toEqual(
      ["dgpu-shared-A", "igpu-inline-cpu4x", "swiftshader-probe"].sort(),
    );
  });

  it.each(fixture.runs.map((r) => [r.leg, r] as const))("e15k01_%s_matches_the_harness", (_, r) => {
    const got = classify(r.windows);
    expect(got.recommendedMaxPanes).toBe(r.expected.recommendedMaxPanes);
    expect(got.recommendedProfile).toBe(r.expected.recommendedProfile);
    expect(got.p95FrameMs).toBeCloseTo(r.expected.p95FrameMs, 6);
  });

  it.each(fixture.runs.map((r) => [r.leg, r] as const))(
    "e15k01_%s_classify_matches_the_mirror_today",
    (_, r) => {
      const got = classify(r.windows);
      const mir = mirror.classify(r.windows);
      expect(got.recommendedMaxPanes).toBe(mir.recommendedMaxPanes);
      expect(got.recommendedProfile).toBe(mir.recommendedProfile);
      expect(got.p95FrameMs).toBe(mir.p95FrameMs);
    },
  );

  it("e15k01_noisy_windows_classify_like_the_mirror", () => {
    // the one-pane window swapped with the four-pane one: the slope guard on both sides
    const r = fixture.runs.find((x) => x.leg === "dgpu-shared-A");
    const [w1, w4] = r?.windows ?? [];
    expect(w1 && w4).toBeTruthy();
    if (!w1 || !w4) return;
    const noisy = [
      { paneCount: 1, frameMs: w4.frameMs },
      { paneCount: 4, frameMs: w1.frameMs },
    ];
    expect(classify(noisy).recommendedMaxPanes).toBe(mirror.classify(noisy).recommendedMaxPanes);
  });

  it("e15k01_weakest_leg_is_reduced_below_the_best", () => {
    const by = (leg: string) => classify(fixture.runs.find((r) => r.leg === leg)?.windows ?? []);
    const best = by("dgpu-shared-A");
    const weak = by("swiftshader-probe");
    expect(weak.recommendedProfile).toBe("reduced");
    expect(weak.recommendedMaxPanes).toBeLessThan(best.recommendedMaxPanes);
  });
});

describe("reducedTrigger on the E15-K01 measured windows, against the mirror's isolated reading", () => {
  const cases = fixture.runs.flatMap((r) =>
    r.windows.map((w) => [`${r.leg}_N${w.paneCount}`, w.frameMs] as const),
  );

  it.each(cases)("e15k01_trigger_%s_matches_the_mirror", (_, frameMs) => {
    const { app, mir } = sameTrigger(timeline(frameMs));
    expect(app.fired).toBe(mir.fired);
    expect(app.p95FrameMs).toBe(mir.p95);
    expect(app.frameCount).toBe(mir.frames);
  });

  it.each(cases)("e15k01_trigger_%s_with_gc_spikes_matches_the_mirror", (_, frameMs) => {
    // one isolated 250 ms frame every 120 frames
    const spiked = timeline(frameMs).map((f, i) => (i % 120 === 60 ? { ...f, frameMs: 250 } : f));
    const { app, mir } = sameTrigger(spiked);
    expect(app.fired).toBe(mir.fired);
    expect(app.p95FrameMs).toBe(mir.p95);
    expect(app.frameCount).toBe(mir.frames);
  });

  it.each(cases)("e15k01_trigger_%s_with_a_hidden_gap_matches_the_mirror", (_, frameMs) => {
    // 30 s of frames, the window hidden for 45 s, then 5 s more: the span is full, the coverage is not
    const gap = (f: TimedFrame) => (f.atMs < 30_000 ? f : { ...f, atMs: f.atMs + 45_000 });
    const frames = timeline(frameMs, 35).map(gap);
    const { app, mir } = sameTrigger(frames);
    expect(app.fired).toBe(mir.fired);
    expect(app.p95FrameMs).toBe(mir.p95);
    expect(app.frameCount).toBe(mir.frames);
  });

  it("e15k01_trigger_fires_on_the_software_gl_four_pane_window_where_the_run_reading_did_not", () => {
    // E15-K01 §9 D-6: every frame here is over 200 ms; dropping them all (the run's reading) never fires
    const w = fixture.runs
      .find((r) => r.leg === "swiftshader-probe")
      ?.windows.find((x) => x.paneCount === 4);
    expect(w).toBeDefined();
    const frames = timeline(w?.frameMs ?? []);
    expect(reducedTrigger(frames).fired).toBe(true);
    expect(mirror.reducedTrigger(asSamples(frames), { outliers: "isolated" }).fired).toBe(true);
    expect(mirror.reducedTrigger(asSamples(frames), { outliers: "all" }).fired).toBe(false);
  });
});
