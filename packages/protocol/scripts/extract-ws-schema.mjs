#!/usr/bin/env node
// Extracts every fenced ```json JSON-Schema block from docs/plan/23-ws-protocol.md
// §13-15 (control frames, public payloads, private payloads) into a single
// machine-readable artefact: docs/plan/ws-schema.json.
//
// The markdown remains human-authoritative; this file is machine-authoritative.
// A doc-drift test (packages/protocol/test/ws-schema-drift.test.ts) forbids the
// two from disagreeing (same pattern as E02-T06's §3 manifest).
//
// Usage: node scripts/extract-ws-schema.mjs [--check [--schema <path>]]
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";
import prettier from "prettier";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, "..", "..", "..");
const mdPath = join(repoRoot, "docs", "plan", "23-ws-protocol.md");
const outPath = join(repoRoot, "docs", "plan", "ws-schema.json");
// `--schema` checks another copy of the artefact, formatted as the tracked one, so the drift test
// tampers with a temp copy and never rewrites docs/plan/ws-schema.json (#2970). Any other argument
// is refused.
function parseArgs(args) {
  if (args.length === 0) return { checkMode: false, schemaPath: outPath };
  if (args.length === 1 && args[0] === "--check") return { checkMode: true, schemaPath: outPath };
  if (args.length === 3 && args[0] === "--check" && args[1] === "--schema" && args[2]) {
    return { checkMode: true, schemaPath: resolve(args[2]) };
  }
  console.error("usage: node scripts/extract-ws-schema.mjs [--check [--schema <path>]]");
  process.exit(2);
}

/** Section heading -> schema group. Only §13-15 carry JSON Schema fences. */
const SECTION_RANGE = {
  start: "## 13. JSON Schemas — control frames",
  end: "## 16. Conformance, limits and test matrix",
};

function extractRange(markdown) {
  const startIdx = markdown.indexOf(SECTION_RANGE.start);
  const endIdx = markdown.indexOf(SECTION_RANGE.end);
  if (startIdx === -1 || endIdx === -1 || endIdx <= startIdx) {
    throw new Error(
      `[extract-ws-schema] could not locate §13-15 bounds in ${mdPath} ` +
        `(start=${startIdx}, end=${endIdx}). The heading text changed — update SECTION_RANGE.`,
    );
  }
  return markdown.slice(startIdx, endIdx);
}

/** Finds every ```json ... ``` fence and parses it as JSON. */
function extractJsonFences(section) {
  const fenceRe = /```json\r?\n([\s\S]*?)\r?\n```/g;
  const results = [];
  let match;
  while ((match = fenceRe.exec(section)) !== null) {
    const raw = match[1];
    let parsed;
    try {
      parsed = JSON.parse(raw);
    } catch (err) {
      throw new Error(
        `[extract-ws-schema] fence at offset ${match.index} is not valid JSON: ${err.message}`,
      );
    }
    results.push(parsed);
  }
  return results;
}

/** Topic catalogue rows from §6, used to cross-check schema coverage. */
function extractTopicCatalogue(markdown) {
  const startIdx = markdown.indexOf("## 6. Topic catalogue");
  const endIdx = markdown.indexOf("## 7. Snapshot");
  const section = markdown.slice(startIdx, endIdx);
  const rowRe = /^\|\s*`([a-z_]+(?:\.[^`|]*)?)`\s*\|.*\|\s*\[`([A-Za-z]+)`\]/gm;
  const topics = [];
  let m;
  while ((m = rowRe.exec(section)) !== null) {
    topics.push({ topicPattern: m[1], payloadSchema: m[2] });
  }
  // Batched aliases (`ticker`, `liquidations`) reuse a schema without a link — capture by name.
  const aliasRe = /^\|\s*`([a-z_]+)`\s*\|[^|]*\|[^|]*\|[^|]*\|\s*`([A-Za-z]+)`/gm;
  let a;
  while ((a = aliasRe.exec(section)) !== null) {
    if (!topics.some((t) => t.topicPattern === a[1])) {
      topics.push({ topicPattern: a[1], payloadSchema: a[2] });
    }
  }
  return topics;
}

async function main() {
  const { checkMode, schemaPath } = parseArgs(process.argv.slice(2));
  const markdown = readFileSync(mdPath, "utf8");
  const section = extractRange(markdown);
  const schemas = extractJsonFences(section);
  const topics = extractTopicCatalogue(markdown);

  if (schemas.length === 0) {
    throw new Error("[extract-ws-schema] extracted zero schemas — parser is broken.");
  }

  const byId = {};
  for (const schema of schemas) {
    if (!schema.$id) {
      throw new Error(
        `[extract-ws-schema] schema titled "${schema.title ?? "?"}" has no $id; every ` +
          `extracted schema must declare one (cv://ws/v1/...).`,
      );
    }
    byId[schema.$id] = schema;
  }

  const artefact = {
    $comment:
      "GENERATED by packages/protocol/scripts/extract-ws-schema.mjs from " +
      "docs/plan/23-ws-protocol.md §13-15. Do not hand-edit — the markdown is " +
      "human-authoritative; this file is machine-authoritative and re-derived by " +
      "`pnpm generate`. A drift test binds the two together.",
    source: "docs/plan/23-ws-protocol.md",
    generatedAt: null,
    schemaCount: schemas.length,
    topicCatalogue: topics,
    schemas: byId,
  };

  const config = (await prettier.resolveConfig(outPath)) ?? {};
  const serialized = await prettier.format(JSON.stringify(artefact, null, 2) + "\n", {
    ...config,
    filepath: outPath,
  });

  if (checkMode) {
    let existing = "";
    try {
      existing = readFileSync(schemaPath, "utf8");
    } catch {
      // Missing file also fails the check.
    }
    if (existing !== serialized) {
      console.error(
        `[extract-ws-schema] ${schemaPath} is stale relative to ${mdPath}. Run ` +
          `\`pnpm --filter @candleviewer/protocol generate\` to regenerate.`,
      );
      process.exit(1);
    }
    console.log(
      `[extract-ws-schema] OK — ws-schema.json matches the markdown (${schemas.length} schemas).`,
    );
    return;
  }

  writeFileSync(outPath, serialized, "utf8");
  console.log(
    `[extract-ws-schema] wrote ${outPath} (${schemas.length} schemas, ${topics.length} topic rows).`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
