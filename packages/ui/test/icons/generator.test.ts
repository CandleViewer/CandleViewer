import { spawnSync } from "node:child_process";
import {
  copyFileSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { afterEach, describe, expect, it, vi } from "vitest";
import {
  componentName,
  iconSources,
  IconSourceError,
  OUTPUT_DIR,
  parseIconSource,
  renderIconModules,
  run,
} from "../../scripts/build-icons.mjs";

const PACKAGE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const SCRIPT = "scripts/build-icons.mjs";
/** A Lucide source's root, as the vendored files carry it (attributes on one line here). */
const ROOT =
  '<svg class="lucide lucide-x" xmlns="http://www.w3.org/2000/svg" width="24" height="24" ' +
  'viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" ' +
  'stroke-linecap="round" stroke-linejoin="round">';
const LICENCE = "<!-- @license lucide-static v1.55.0 - ISC -->";
/** A source drawing `body` under `root`, with no comment before it. */
const unlicensed = (body: string, root = ROOT): string => `${root}\n${body}\n</svg>\n`;
/** A source drawing `body` under `root`, after the upstream licence comment. */
const source = (body: string, root = ROOT): string => `${LICENCE}\n${unlicensed(body, root)}`;
/** The file a rejected source is read from: each failure names it first. */
const BAD = "src/icons/source/lucide/bad.svg";
/** A plain element of each geometry tag the parser allows, with every attribute it may carry. */
const SHAPES: Readonly<Record<string, Readonly<Record<string, string>>>> = {
  path: { d: "M3 12h18" },
  circle: { cx: "12", cy: "12", r: "3" },
  ellipse: { cx: "12", cy: "12", rx: "10", ry: "6" },
  line: { x1: "4", y1: "12", x2: "20", y2: "12" },
  polyline: { points: "4 12 12 4 20 12" },
  polygon: { points: "12 3 21 20 3 20" },
  rect: { x: "3", y: "3", width: "18", height: "18", rx: "2", ry: "2" },
};
/** What no geometry element may carry: paint, a style, a script, a reference or a move. */
const FORBIDDEN: Readonly<Record<string, string>> = {
  fill: "#000000",
  stroke: "red",
  "stroke-width": "3",
  opacity: "0.5",
  style: "stroke: red",
  class: "accent",
  onclick: "run()",
  href: "#glyph",
  "xlink:href": "#glyph",
  transform: "rotate(45)",
  "clip-path": "url(#clip)",
};
/** `<tag name="value" ... />`, the attributes in order. */
const element = (tag: string, attributes: Readonly<Record<string, string>>): string =>
  `<${tag} ${Object.entries(attributes)
    .map(([name, value]) => `${name}="${value}"`)
    .join(" ")} />`;
/** `node <entry>/scripts/build-icons.mjs ...args` in a child process, as `build` runs it. */
function command(entry: string, ...args: string[]) {
  const script = path.join(entry, SCRIPT);
  const { status, stdout, stderr } = spawnSync(process.execPath, [script, ...args], {
    cwd: tmpdir(),
    encoding: "utf-8",
    // A synchronous child can't be pre-empted by vitest's timeout; bound it here.
    timeout: 30_000,
    killSignal: "SIGKILL",
  });
  return { status, stdout, stderr };
}

describe("the icon generator's drift check (scripts/build-icons.mjs)", () => {
  it("left src/icons/generated/ as it renders it: no stale, missing, extra or hand-edited module", () => {
    const modules = renderIconModules();
    const written = readdirSync(path.join(PACKAGE, OUTPUT_DIR)).map((f) => `${OUTPUT_DIR}/${f}`);
    expect(written.sort()).toEqual([...modules.keys()].sort());
    for (const [file, content] of modules) {
      const committed = readFileSync(path.join(PACKAGE, file), "utf-8");
      expect(committed, `${file} is stale: run pnpm --filter @candleviewer/ui build:icons`).toBe(
        content,
      );
    }
  });

  it("passes build's check: build:icons --check, run as a command, exits 0 on this package", () => {
    expect(command(PACKAGE, "--check")).toEqual({ status: 0, stdout: "", stderr: "" });
  });

  it("renders the same bytes on every run: name order, no timestamp, one module per icon", () => {
    const modules = renderIconModules();
    expect([...renderIconModules()]).toEqual([...modules]);
    const names = iconSources().map(({ name }) => name);
    expect([...modules.keys()]).toEqual([
      ...names.map((name) => `${OUTPUT_DIR}/${componentName(name)}.tsx`),
      `${OUTPUT_DIR}/components.ts`,
    ]);
    for (const [file, content] of modules) {
      expect(content, file).not.toMatch(/\d{4}-\d{2}-\d{2}|\d{2}:\d{2}:\d{2}/);
      expect(content.startsWith("// GENERATED by packages/ui/scripts/build-icons.mjs"), file).toBe(
        true,
      );
    }
  });

  it("finds every source under its origin, sorted by name", () => {
    const sources = iconSources();
    expect(sources.map(({ name }) => name)).toEqual(sources.map(({ name }) => name).sort());
    for (const { name, origin, file } of sources) {
      expect(file).toBe(`src/icons/source/${origin}/${name}.svg`);
    }
  });

  it("keeps a source's geometry in order, the Lucide glyph its class names and its licence", () => {
    const parsed = parseIconSource(
      source('  <path d="M18 6 6 18" />\n  <circle cx="12" cy="12" r="3" />'),
      "close.svg",
    );
    expect(parsed).toEqual({
      glyph: "x",
      licence: "lucide-static v1.55.0 - ISC",
      children: [
        ["path", [["d", "M18 6 6 18"]]],
        [
          "circle",
          [
            ["cx", "12"],
            ["cy", "12"],
            ["r", "3"],
          ],
        ],
      ],
    });
  });

  it("accepts a custom glyph's root without a Lucide class or a licence line", () => {
    const root = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none">';
    const parsed = parseIconSource(
      unlicensed('<line x1="4" y1="12" x2="20" y2="12" />', root),
      "a.svg",
    );
    expect(parsed.glyph).toBeNull();
    expect(parsed.licence).toBeNull();
    expect(parsed.children).toEqual([
      [
        "line",
        [
          ["x1", "4"],
          ["y1", "12"],
          ["x2", "20"],
          ["y2", "12"],
        ],
      ],
    ]);
  });

  it.each(Object.entries(SHAPES))(
    "accepts a plain <%s>, keeping its attributes in order",
    (tag, attributes) => {
      expect(parseIconSource(source(element(tag, attributes)), "a.svg").children).toEqual([
        [tag, Object.entries(attributes)],
      ]);
    },
  );

  it("collapses each value's spacing to one space, trimmed, as a module prints it", () => {
    const parsed = parseIconSource(
      source(
        '<path d="\n    M3 12h18\r\n    M12 3\t\tv18 " />\n<polygon points=" 12 3  21 20\n3 20" />',
      ),
      "a.svg",
    );
    expect(parsed.children).toEqual([
      ["path", [["d", "M3 12h18 M12 3 v18"]]],
      ["polygon", [["points", "12 3 21 20 3 20"]]],
    ]);
  });

  // A source is data: the allowlist keeps the geometry of a 24x24 outline and fails on anything
  // that could run, fetch, restyle or move a glyph off the grid (the ticket's security note).
  it.each([
    ["an element that is not geometry", source("<script />")],
    ["an external reference", source('<use href="#glyph" />')],
    ["an embedded image", source('<image href="glyph.png" width="24" height="24" />')],
    ["embedded markup", source("<foreignObject />")],
    ["a group", source('<g><path d="M0 0h24" /></g>')],
    ["text", source("<text>A</text>")],
    ["an attribute named like a prototype key", source('<path d="M0 0h24" constructor="x" />')],
    ["an element named like a prototype key", source('<constructor d="M0 0h24" />')],
    ["a repeated attribute", source('<path d="M0 0h24" d="M0 0v24" />')],
    ["an entity in a value", source('<path d="M0 0h24&amp;" />')],
    ["path data that is not path data", source('<path d="url(#a)" />')],
    ["a coordinate that is not a number", source('<circle cx="12px" cy="12" r="3" />')],
    ["geometry without its required attribute", source('<circle cx="12" cy="12" />')],
    ["a child with content", source('<path d="M0 0h24"></path>')],
    ["no geometry at all", source("")],
    [
      "a root that is not 24x24",
      source('<path d="M0 0h16" />', ROOT.replace("0 0 24 24", "0 0 16 16")),
    ],
    ["a root without a viewBox", source('<path d="M0 0h24" />', '<svg fill="none">')],
    [
      "a hardcoded root colour",
      source('<path d="M0 0h24" />', ROOT.replace("currentColor", "#fff")),
    ],
    ["a root fill", source('<path d="M0 0h24" />', ROOT.replace('fill="none"', 'fill="black"'))],
    ["a root event handler", source('<path d="M0 0h24" />', ROOT.replace(">", ' onload="run()">'))],
    ["a document type", `<!DOCTYPE svg>\n${source('<path d="M0 0h24" />')}`],
    ["markup after the root", `${source('<path d="M0 0h24" />')}<svg />`],
    ["a comment inside the root", source('<!-- note -->\n<path d="M0 0h24" />')],
  ])("rejects %s, naming the file", (_, text) => {
    const parse = () => parseIconSource(text, BAD);
    expect(parse).toThrow(IconSourceError);
    expect(parse).toThrow(/^src\/icons\/source\/lucide\/bad\.svg: /);
  });

  // A module repeats the licence line in a comment of its own: only lucide-static's line, once.
  it.each([
    ["a licence line that is not lucide-static's", "<!-- @license feather v4.29.0 - MIT -->"],
    [
      "a licence line that would end its module's comment",
      "<!-- @license lucide-static v1.55.0 - ISC */ run(); /* -->",
    ],
  ])("rejects %s, naming the file", (_, line) => {
    expect(() => parseIconSource(`${line}\n${unlicensed('<path d="M0 0h24" />')}`, BAD)).toThrow(
      `${BAD}: its @license line is not "@license lucide-static v<version> - ISC"`,
    );
  });

  it("rejects a repeated licence line, naming the file", () => {
    expect(() => parseIconSource(`${LICENCE}\n${source('<path d="M0 0h24" />')}`, BAD)).toThrow(
      `${BAD}: repeats its @license line`,
    );
  });

  // Each geometry tag refuses what could paint, restyle, run, fetch or move it: the grid alone
  // paints a glyph, so a module keeps nothing but its geometry.
  it.each(
    Object.entries(SHAPES).flatMap(([tag, attributes]) =>
      Object.entries(FORBIDDEN).map(([name, value]): [string, string, Record<string, string>] => [
        tag,
        name,
        { ...attributes, [name]: value },
      ]),
    ),
  )("rejects <%s> carrying %s, naming the file", (tag, name, attributes) => {
    expect(() => parseIconSource(source(element(tag, attributes)), BAD)).toThrow(
      `${BAD}: <${tag}> may not carry ${name}`,
    );
  });

  // XML whitespace alone spaces a source: any other space hides in a value, and `\s` would read it
  // as spacing.
  it.each([
    ["a no-break space in path data", source('<path d="M0 0\u00a0h24" />'), "U+00A0 on line 3"],
    [
      "a thin space in points",
      source('<polyline points="4 12\u2009 20 12" />'),
      "U+2009 on line 3",
    ],
    [
      "an ideographic space between attributes",
      source('<circle cx="12"\u3000cy="12" r="3" />'),
      "U+3000 on line 3",
    ],
    [
      "a line separator in a root value",
      source('<path d="M0 0h24" />', ROOT.replace('width="24"', 'width="24\u2028"')),
      "U+2028 on line 2",
    ],
    ["a form feed", source('<path d="M0 0h24" />\f<path d="M0 0v24" />'), "U+000C on line 3"],
    ["a byte-order mark", `\ufeff${source('<path d="M0 0h24" />')}`, "U+FEFF on line 1"],
  ])("rejects %s, naming the file, the character and its line", (_, text, where) => {
    expect(() => parseIconSource(text, BAD)).toThrow(
      `${BAD}: ${where} is not XML whitespace (space, tab, CR or LF)`,
    );
  });

  it("names a component after its icon", () => {
    expect(componentName("close")).toBe("CloseIcon");
    expect(componentName("chevrons-up-down")).toBe("ChevronsUpDownIcon");
    expect(componentName("zoom-in")).toBe("ZoomInIcon");
  });
});

describe("the generator on a source tree (iconSources, run, the command line)", () => {
  const trees: string[] = [];
  /** A package root holding `files` (paths under src/icons/source/) in a fresh temp directory. */
  const tree = (...files: string[]) => {
    const root = mkdtempSync(path.join(tmpdir(), "cv-icon-sources-"));
    trees.push(root);
    for (const file of files) {
      mkdirSync(path.dirname(path.join(root, "src/icons/source", file)), { recursive: true });
      writeFileSync(path.join(root, "src/icons/source", file), source('<path d="M0 0h24" />'));
    }
    return root;
  };
  afterEach(() => {
    vi.restoreAllMocks();
    trees.splice(0).forEach((root) => rmSync(root, { recursive: true }));
  });

  it("reads each origin's sources, past its licence notice", () => {
    const root = tree("lucide/LICENSE", "lucide/close.svg", "custom/twap.svg");
    expect(iconSources(root)).toEqual([
      { name: "close", origin: "lucide", file: "src/icons/source/lucide/close.svg" },
      { name: "twap", origin: "custom", file: "src/icons/source/custom/twap.svg" },
    ]);
  });

  it("renders a source whose values span lines as the same source on one line", () => {
    const root = tree("custom/twap.svg");
    const file = path.join(root, "src/icons/source/custom/twap.svg");
    writeFileSync(file, source('<path d="M3 12h18 M12 3v18" />'));
    const oneLine = renderIconModules(root);
    writeFileSync(file, source('<path\n  d="\n    M3 12h18\n    M12 3v18\n  "\n/>'));
    expect(renderIconModules(root)).toEqual(oneLine);
  });

  // SEC-271B-01: the module repeats the version its source's own line names, never a fixed one,
  // right above the component (Rollup drops a comment that leads an import it removes).
  it("repeats a source's licence line as a legal comment above the component it draws", () => {
    const root = tree("lucide/close.svg", "custom/twap.svg");
    const lucide = path.join(root, "src/icons/source/lucide/close.svg");
    writeFileSync(lucide, source('<path d="M0 0h24" />').replace("v1.55.0", "v9.8.7"));
    writeFileSync(
      path.join(root, "src/icons/source/custom/twap.svg"),
      unlicensed('<path d="M0 0h24" />'),
    );
    const modules = renderIconModules(root);
    expect(modules.get(`${OUTPUT_DIR}/CloseIcon.tsx`)).toContain(
      '";\n\n/*! @license lucide-static v9.8.7 - ISC (see packages/ui/src/icons/source/lucide/LICENSE) */\n' +
        "/** The `close` icon:",
    );
    expect(modules.get(`${OUTPUT_DIR}/TwapIcon.tsx`)).not.toContain("@license");
    expect(modules.get(`${OUTPUT_DIR}/components.ts`)).not.toContain("@license");
  });

  it("fails on a Lucide source without its licence line, naming the file", () => {
    const root = tree("lucide/close.svg");
    writeFileSync(
      path.join(root, "src/icons/source/lucide/close.svg"),
      unlicensed('<path d="M0 0h24" />'),
    );
    expect(() => renderIconModules(root)).toThrow(
      'src/icons/source/lucide/close.svg: a Lucide source needs its "@license lucide-static v<version> - ISC" line',
    );
  });

  it("writes a tree's modules, finds them in sync, and repairs a hand-edit or a stray file", () => {
    const root = tree("lucide/close.svg", "custom/twap.svg");
    const logs = vi.spyOn(console, "log").mockImplementation(() => undefined);
    const errors = vi.spyOn(console, "error").mockImplementation(() => undefined);
    expect(run(["--check"], root)).toBe(1); // nothing generated yet
    expect(run([], root)).toBe(0);
    expect(readdirSync(path.join(root, OUTPUT_DIR)).sort()).toEqual([
      "CloseIcon.tsx",
      "TwapIcon.tsx",
      "components.ts",
    ]);
    expect(run(["--check"], root)).toBe(0);
    writeFileSync(path.join(root, OUTPUT_DIR, "CloseIcon.tsx"), "// edited by hand\n");
    writeFileSync(path.join(root, OUTPUT_DIR, "Stray.tsx"), "");
    errors.mockClear();
    expect(run(["--check"], root)).toBe(1);
    expect(errors.mock.calls.slice(0, 2)).toEqual([
      [`stale or missing: ${OUTPUT_DIR}/CloseIcon.tsx`],
      [`not generated: ${OUTPUT_DIR}/Stray.tsx`],
    ]);
    expect(run([], root)).toBe(0);
    expect(logs.mock.calls.at(-1)).toEqual(["[icons] 3 modules: 1 written, 1 deleted"]);
    expect(run(["--check"], root)).toBe(0);
  });

  // `build` runs `build:icons --check`: a command that exits 0 having checked nothing would ship a
  // stale module. It acts the same run through a symlink to its path (a junction on Windows).
  it.each(["its real path", "a symlinked path"])(
    "runs as a command through %s: writes a tree, then --check exits 1 naming a hand-edit",
    (via) => {
      const root = tree("lucide/close.svg");
      mkdirSync(path.join(root, "scripts"));
      copyFileSync(path.join(PACKAGE, SCRIPT), path.join(root, SCRIPT));
      const entry = via === "its real path" ? root : path.join(tree(), "link");
      if (entry !== root) symlinkSync(root, entry, "junction");
      expect(command(entry)).toEqual({
        status: 0,
        stdout: "[icons] 2 modules: 2 written, 0 deleted\n",
        stderr: "",
      });
      expect(command(entry, "--check")).toEqual({ status: 0, stdout: "", stderr: "" });
      writeFileSync(path.join(root, OUTPUT_DIR, "CloseIcon.tsx"), "// edited by hand\n");
      expect(command(entry, "--check")).toEqual({
        status: 1,
        stdout: "",
        stderr:
          `stale or missing: ${OUTPUT_DIR}/CloseIcon.tsx\n` +
          'Regenerate: pnpm --filter @candleviewer/ui build:icons (packages/ui/README.md, "Icons")\n',
      });
    },
  );

  it("runs nothing when imported, whatever argv[1] holds", () => {
    const url = pathToFileURL(path.join(PACKAGE, SCRIPT)).href;
    const imported = spawnSync(
      process.execPath,
      ["--input-type=module", "-e", `await import(${JSON.stringify(url)});`, "not-a-path"],
      { cwd: tree(), encoding: "utf-8" },
    );
    expect([imported.status, imported.stdout, imported.stderr]).toEqual([0, "", ""]);
  });

  it("reports a rejected source in one line naming the file, not a stack trace", () => {
    const root = tree("custom/twap.svg");
    writeFileSync(path.join(root, "src/icons/source/custom/twap.svg"), source("<g />"));
    const errors = vi.spyOn(console, "error").mockImplementation(() => undefined);
    expect(run([], root)).toBe(1);
    expect(errors.mock.calls).toEqual([
      ["src/icons/source/custom/twap.svg: <g> is not a geometry element"],
    ]);
    expect(run(["--write"], root)).toBe(1);
    expect(errors.mock.calls.at(-1)).toEqual(["usage: node scripts/build-icons.mjs [--check]"]);
  });

  it.each([
    ["a directory that is not an origin", ["phosphor/close.svg"], /phosphor: not an origin/],
    ["a file that is not a kebab-case SVG", ["lucide/Close.svg"], /Close\.svg: not a kebab-case/],
    ["a stray file", ["lucide/README.md"], /README\.md: not a kebab-case/],
    ["two names with one component", ["lucide/a1b.svg", "custom/a-1b.svg"], /clashes with/],
  ])("fails on %s", (_, files, message) => {
    expect(() => iconSources(tree(...files))).toThrow(message);
  });
});

// SEC-271B-01: the Lucide glyphs ship with their licence. Each notice is built here from its
// source's own line, not through the generator, then looked for in the modules and in a tsup build.
describe("the Lucide licence notice, in the committed modules and the package build", () => {
  const LUCIDE = "src/icons/source/lucide";
  /** Each Lucide source, and the notice its module carries: the version its own line names. */
  const notices = () =>
    readdirSync(path.join(PACKAGE, LUCIDE))
      .filter((entry) => entry.endsWith(".svg"))
      .map((entry) => {
        const svg = readFileSync(path.join(PACKAGE, LUCIDE, entry), "utf-8");
        const [, version = "?"] =
          /^<!-- @license lucide-static v(\d+\.\d+\.\d+) - ISC -->\n/.exec(svg) ?? [];
        const notice = `/*! @license lucide-static v${version} - ISC (see packages/ui/${LUCIDE}/LICENSE) */`;
        return { file: `${LUCIDE}/${entry}`, notice };
      });
  /** tsup with the package's own tsup.config.ts, into argv[1]: no declarations, no CSS copy. */
  const BUILD =
    'const { build } = await import("tsup");\n' +
    "await build({ outDir: process.argv[1], dts: false, silent: true, onSuccess: async () => {} });";

  it("leads the component of every Lucide glyph's module, with its source's version", () => {
    const modules = readdirSync(path.join(PACKAGE, OUTPUT_DIR)).map((entry) =>
      readFileSync(path.join(PACKAGE, OUTPUT_DIR, entry), "utf-8"),
    );
    const lucide = notices();
    expect(lucide.length).toBeGreaterThan(0);
    for (const { file, notice } of lucide) {
      // The one module whose header names this source.
      const owned = modules.filter((content) => content.includes(`\n// ${file} (`));
      expect(owned, file).toHaveLength(1);
      const lines = (owned[0] ?? "").split("\n");
      const component = lines.findIndex((line) => line.startsWith("export function "));
      expect(lines.slice(component - 2, component), file).toEqual([
        notice,
        expect.stringMatching(/^\/\*\* The `[\da-z-]+` icon: /),
      ]);
      const licences = lines.filter((line) => line.includes("@license"));
      expect(licences, file).toEqual([notice]);
    }
  });

  it("keeps each notice through a tsup build of the package", { timeout: 60_000 }, () => {
    const outDir = mkdtempSync(path.join(tmpdir(), "cv-icon-tsup-"));
    try {
      const built = spawnSync(process.execPath, ["--input-type=module", "-e", BUILD, outDir], {
        cwd: PACKAGE,
        encoding: "utf-8",
        // Under the test's own 60 s, which can't pre-empt a synchronous child.
        timeout: 50_000,
        killSignal: "SIGKILL",
      });
      expect(built.status, built.stderr).toBe(0);
      // esbuild moves each legal comment to the end of the bundle, once per distinct text.
      const bundle = readFileSync(path.join(outDir, "index.js"), "utf-8");
      for (const notice of new Set(notices().map((lucide) => lucide.notice))) {
        expect(bundle).toContain(`\n${notice}\n`);
      }
    } finally {
      rmSync(outDir, { recursive: true, force: true });
    }
  });
});
