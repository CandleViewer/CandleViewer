"""E08-S08 (#4702): the CV `ticker` golden the web client's tests replay (pre-ruling 3; C-13.5).

The golden is derived, never written by hand: the recorded venue captures go through the shipped
mapper, E08-T08's path from a raw frame to a §14.8 `TickerUpdate` item:

- `ws/recorded_tickers_BTCUSDT.jsonl` (a snapshot and 19 deltas, 100 ms apart): each frame through
  `parse_ticker_frame`, then `TickerMerger.apply` (the stream's merged state), then `ticker_item`;
- the three recorded `GET /v5/market/tickers` replies: each through `parse_tickers_reply`, then
  `ticker_event`, then `ticker_item`.

One line per mapper output, keys sorted: the capture it came from and the §14.8 body it maps to,
every body valid against `cv://ws/v1/ticker.schema.json`. The golden is stale when a source's
bytes change (the manifest pins each sha256) or when the mapper's output differs from the
committed lines; either fails here. `CV_REGEN_GOLDEN=1` rewrites the golden and its manifest, and
takes the mapper's commit from `CV_GOLDEN_MAPPER_COMMIT` (the manifest's `regenerate` line).
"""

from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
from typing import Any

from candleviewer.exchange.bybit.ticker import parse_ticker_frame
from candleviewer.exchange.bybit.tickers import parse_tickers_reply
from candleviewer.ingestion.ticker_stream import TickerMerger, ticker_event
from candleviewer.ingestion.ticker_topic import ticker_item
from tests._corpus import CORPUS_ROOT, corpus_path, frames, rest
from tests.contract.ws._harness import check_schema

SCHEMA = "cv://ws/v1/ticker.schema.json"
FIXTURES = CORPUS_ROOT.parent
GOLDEN_DIR = FIXTURES / "golden" / "ticker"
GOLDEN = GOLDEN_DIR / "ticker_items.jsonl"
MANIFEST = GOLDEN_DIR / "manifest.json"
WS_SOURCE = "ws/recorded_tickers_BTCUSDT.jsonl"
REST_SOURCES = tuple(f"rest/recorded_tickers_{s}.json" for s in ("BTCUSDT", "ETHUSDT", "SOLUSDT"))
#: The mapper the lines come from: the venue parsers, the merged state and the §14.8 item.
MAPPER = (
    "services/api/candleviewer/exchange/bybit/ticker.py",
    "services/api/candleviewer/exchange/bybit/tickers.py",
    "services/api/candleviewer/ingestion/ticker_stream.py",
    "services/api/candleviewer/ingestion/ticker_topic.py",
)
REGENERATE = (
    "cd services/api && CV_REGEN_GOLDEN=1 "
    f'CV_GOLDEN_MAPPER_COMMIT="$(git -C ../.. log -1 --format=%H -- {" ".join(MAPPER)})" '
    "uv run pytest tests/unit/exchange/bybit/test_ticker_cv_golden.py"
)
#: The time of ingest is not in the item; a fixed value keeps the derivation free of the wall clock.
INGEST_US = 1


def _rel(path: Path) -> str:
    return path.relative_to(FIXTURES).as_posix()


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _line(source: str, item: dict[str, Any]) -> str:
    return json.dumps(
        {"body": {"tickers": [item]}, "source": source}, sort_keys=True, separators=(",", ":")
    )


def _derive() -> list[str]:
    """Every line of the golden, in source order: the stream capture, then each REST reply."""
    lines: list[str] = []
    merger = TickerMerger()
    ws = _rel(corpus_path(WS_SOURCE))
    for n, raw in enumerate(frames(WS_SOURCE), start=1):
        delta = parse_ticker_frame(raw)
        assert delta is not None, f"{WS_SOURCE}:{n} is no ticker frame"
        event = merger.apply(delta, ts_ingest_us=INGEST_US)
        assert event is not None, f"{WS_SOURCE}:{n} leaves the merged state incomplete"
        lines.append(_line(f"{ws}:{n}", ticker_item(event, stale=False)))
    for source in REST_SOURCES:
        page = parse_tickers_reply(rest(source))
        assert page.rejected == 0, f"{source}: a row was rejected"
        for symbol, delta in page.tickers.items():
            event = ticker_event(
                symbol, delta.fields, ts_event_us=delta.ts_event_us, ts_ingest_us=INGEST_US
            )
            lines.append(_line(_rel(corpus_path(source)), ticker_item(event, stale=False)))
    return lines


def _manifest(text: str, commit: str) -> str:
    sources = {_rel(corpus_path(s)): _sha256(corpus_path(s)) for s in (WS_SOURCE, *REST_SOURCES)}
    doc = {
        "$note": (
            "GENERATED by services/api/tests/unit/exchange/bybit/test_ticker_cv_golden.py: do not "
            "hand-edit. CV ticker items derived from the recorded captures below through the "
            "shipped mapper; regenerate with the command below and review the diff."
        ),
        "golden": {GOLDEN.name: hashlib.sha256(text.encode("utf-8")).hexdigest()},
        "mapper": {"commit": commit, "files": list(MAPPER)},
        "regenerate": REGENERATE,
        "schema": SCHEMA,
        "sources": sources,
    }
    return json.dumps(doc, indent=2, sort_keys=True) + "\n"


def _committed_commit() -> str:
    data: dict[str, Any] = json.loads(MANIFEST.read_text(encoding="utf-8"))
    return str(data["mapper"]["commit"])


def test_every_derived_body_is_a_ticker_update() -> None:
    for line in _derive():
        check_schema(SCHEMA, json.loads(line)["body"], "a golden ticker body")


def test_the_stream_capture_maps_to_one_item_per_frame_and_each_rest_reply_to_one() -> None:
    lines = [json.loads(line) for line in _derive()]
    symbols = [line["body"]["tickers"][0]["symbol"] for line in lines]
    assert symbols == ["BTCUSDT"] * len(frames(WS_SOURCE)) + ["BTCUSDT", "ETHUSDT", "SOLUSDT"]
    first = lines[0]["body"]["tickers"][0]
    # the recorded snapshot's own values, as the wire's decimal strings (§14.8)
    assert (first["last_price"], first["bid1_price"], first["ask1_price"]) == (
        "82751.20",
        "82751.10",
        "82751.20",
    )
    assert first["ts_ms"] == json.loads(frames(WS_SOURCE)[0])["ts"]
    assert all(line["body"]["tickers"][0]["stale"] is False for line in lines)


def test_the_committed_golden_is_the_mapper_output_of_the_pinned_captures() -> None:
    text = "\n".join(_derive()) + "\n"
    if os.environ.get("CV_REGEN_GOLDEN") == "1":
        commit = os.environ.get("CV_GOLDEN_MAPPER_COMMIT", "").strip()
        assert len(commit) == 40, f"regenerate with: {REGENERATE}"
        GOLDEN_DIR.mkdir(parents=True, exist_ok=True)
        GOLDEN.write_text(text, encoding="utf-8", newline="\n")
        MANIFEST.write_text(_manifest(text, commit), encoding="utf-8", newline="\n")
    assert GOLDEN.read_text(encoding="utf-8") == text, f"stale golden; regenerate: {REGENERATE}"
    expected = _manifest(text, _committed_commit())
    assert MANIFEST.read_text(encoding="utf-8") == expected, f"stale manifest: {REGENERATE}"
