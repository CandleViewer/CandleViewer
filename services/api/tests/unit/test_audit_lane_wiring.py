@pytest.mark.parametrize("name", ["CV_AUDIT_LANE_KEY_HEX", "CV_AUDIT_LANE_PREVIOUS_KEY_HEX"])
def test_an_environment_key_in_the_env_file_is_refused_at_load(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path, key_hex: str, name: str
) -> None:
    """`Settings` forbids undeclared input from `.env`, and its message hides the value. An empty
    line carries no key material: pydantic-settings drops it, and nothing refuses it."""
    monkeypatch.chdir(tmp_path)
    (tmp_path / ".env").write_text(f"{name}=\n", encoding="ascii")
    Settings()  # the empty line is dropped, not refused
    (tmp_path / ".env").write_text(f"{name}={key_hex}\n", encoding="ascii")

    with pytest.raises(ValidationError, match=name.lower()) as refused:
        Settings()
    assert key_hex not in str(refused.value)


def test_lane_key_loader_hands_the_audit_service_the_key_bytes(
    tmp_path: Path, key_hex: str
) -> None:
    root = tmp_path.resolve()
    key = _key_file(root / "secrets" / "k1", key_hex.encode())

    assert wiring.lane_key_loader(_real(root, CV_AUDIT_LANE_KEY_FILE=key))() == (
        bytes.fromhex(key_hex),
        None,
    )
    assert wiring.lane_key_loader(Settings())() is None  # the fake backend reads no key


