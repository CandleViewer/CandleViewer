"""ADR-0037 decision 6 (#3009 S2b-1): the composition root reads the audit lane key.

The key files' checks (`24-internal-schemas.md` §15.6), and each boot refusal that needs no open
lane: the environment form, no key while a real audit backend is wired, a key shared with an auth
secret, a key file under the directory of `CV_AUDIT_WAL_PATH`. `AuditService.start()` runs it at
boot (S2b-2a). Every key here is generated by the test, and every file is in `tmp_path`.
"""

