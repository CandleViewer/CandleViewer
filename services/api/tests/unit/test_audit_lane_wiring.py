@pytest.mark.parametrize("secret", SECRETS)
@pytest.mark.parametrize(("variable", "index"), [(KEY_FILE, 0), (PREVIOUS_KEY_FILE, 1)])
def test_a_lane_key_equal_to_an_auth_key_or_the_pepper_refuses_boot(
    key_hex: str, secret: str, variable: str, index: int
) -> None:
    keys = [secrets.token_bytes(32), secrets.token_bytes(32)]
    keys[index] = bytes.fromhex(key_hex)
    configured: dict[str, Any] = {secret: SecretStr(key_hex.upper())}
    settings = Settings(**configured)

    with pytest.raises(LaneKeyRefused, match=f"^{variable} must hold a key of its own, "):
        refuse_reused_key(settings, keys[0], keys[1])


def test_a_pepper_equal_to_the_raw_key_bytes_refuses_boot() -> None:
    key = secrets.token_hex(16).encode()  # 32 bytes that are also text, as an env value is

    with pytest.raises(LaneKeyRefused, match=f"^{KEY_FILE} must hold a key of its own, "):
        refuse_reused_key(Settings(auth_pepper=SecretStr(key.decode())), key, None)


def test_a_lane_key_of_its_own_passes(key_hex: str) -> None:
    others: dict[str, Any] = {name: SecretStr(secrets.token_hex(32)) for name in SECRETS[:-1]}
    settings = Settings(**others, auth_pepper=SecretStr("not-the-key"))

    refuse_reused_key(settings, bytes.fromhex(key_hex), secrets.token_bytes(32))


def test_the_reuse_check_runs_every_comparison_in_constant_time(
    monkeypatch: pytest.MonkeyPatch, key_hex: str
) -> None:
    """Five secrets, each as text and decoded: no early exit once the first one matches."""
    key = bytes.fromhex(key_hex)
    others: dict[str, Any] = {name: SecretStr(secrets.token_hex(32)) for name in SECRETS[1:]}
    settings = Settings(auth_totp_key_hex=SecretStr(key_hex), **others)
    seen = _record(monkeypatch, hmac, "compare_digest")

    with pytest.raises(LaneKeyRefused):
        refuse_reused_key(settings, key, None)
    assert (key, key) in seen
    assert len(seen) == 10


@pytest.mark.parametrize(
    ("wal", "settings"),
    [
        ("{root}/audit/a.wal", {KEY_FILE: "{root}/audit/lane/k"}),
        ("{root}/audit/a.wal", {PREVIOUS_KEY_FILE: "{root}/audit/k0"}),
        ("var/a.wal", {KEY_FILE: "{root}/var/k"}),
        ("{root}/link/a.wal", {KEY_FILE: "{root}/secrets/k"}),
    ],
    ids=["current", "previous", "relative-wal", "symlinked-audit-dir"],
)
def test_a_key_file_under_the_audit_wal_directory_refuses_boot(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path, wal: str, settings: dict[str, str]
) -> None:
    """Both paths resolved: a relative WAL path against the working directory, as cv-api does,
    and a symlinked audit directory to where it points."""
    root = tmp_path.resolve()
    (root / "secrets").mkdir()
    (root / "link").symlink_to(root / "secrets")
    monkeypatch.chdir(root)
    files: dict[str, Any] = {
        variable: path.format(root=root) for variable, path in settings.items()
    }
    configured = Settings(audit_wal_path=wal.format(root=root), **files)

    with pytest.raises(LaneKeyRefused, match=f"^{next(iter(files))} {UNDER}: "):
        refuse_key_under_audit_dir(configured)


def test_a_key_file_beside_the_audit_wal_directory_passes(tmp_path: Path) -> None:
    root = tmp_path.resolve()
    settings = _real(
        root,
        CV_AUDIT_LANE_KEY_FILE=str(root / "audit-keys" / "k"),
        CV_AUDIT_LANE_PREVIOUS_KEY_FILE=str(root / "k0"),
    )

    refuse_key_under_audit_dir(settings)


def test_load_lane_keys_reads_both_keys_and_shows_only_their_ids(
    tmp_path: Path, key_hex: str
) -> None:
    root = tmp_path.resolve()
    previous_hex = secrets.token_hex(32)
    settings = _real(
        root,
        CV_AUDIT_LANE_KEY_FILE=_key_file(root / "secrets" / "k1", key_hex.encode() + b"\n"),
        CV_AUDIT_LANE_PREVIOUS_KEY_FILE=_key_file(root / "secrets" / "k0", previous_hex.encode()),
    )

    keys = load_lane_keys(settings, environ={})

    assert keys is not None
    assert (keys.current, keys.previous) == (bytes.fromhex(key_hex), bytes.fromhex(previous_hex))
    assert (keys.kid, keys.previous_kid) == (key_id(keys.current), key_id(keys.previous or b""))
    assert repr(keys) == f"LaneKeyMaterial(kid={keys.kid!r}, previous_kid={keys.previous_kid!r})"


@pytest.mark.parametrize(
    ("settings", "environ", "message"),
    [
        ({}, {"CV_AUDIT_LANE_KEY_HEX": "x"}, "CV_AUDIT_LANE_KEY_HEX is refused: "),
        ({KEY_FILE: "{root}/s/absent"}, {}, f"{KEY_FILE} names no file"),
        ({PREVIOUS_KEY_FILE: "{root}/s/absent"}, {}, f"{PREVIOUS_KEY_FILE} names no file"),
        ({KEY_FILE: "{root}/audit/k"}, {}, f"{KEY_FILE} {UNDER}: "),
        ({KEY_FILE: "{root}/s/short"}, {}, f"{KEY_FILE} {CONTENT}"),
        ({"auth_pepper": "{key}"}, {}, f"{KEY_FILE} must hold a key of its own, "),
    ],
    ids=["environment", "no-key", "no-previous-key", "under-audit-dir", "content", "reused"],
)
def test_load_lane_keys_runs_every_refusal(
    tmp_path: Path, key_hex: str, settings: dict[str, str], environ: dict[str, str], message: str
) -> None:
    root = tmp_path.resolve()
    _key_file(root / "s" / "short", key_hex[:63].encode())
    _key_file(root / "audit" / "k", key_hex.encode())
    configured = {KEY_FILE: _key_file(root / "s" / "k", key_hex.encode())} | {
        name: value.format(root=root, key=key_hex) for name, value in settings.items()
    }

    assert str(_refusal(_real(root, **configured), environ)).startswith(message)


def test_the_key_never_reaches_a_log_record_or_a_refusal(
    caplog: pytest.LogCaptureFixture, tmp_path: Path, key_hex: str
) -> None:
    root = tmp_path.resolve()
    good = _real(root, CV_AUDIT_LANE_KEY_FILE=_key_file(root / "s" / "k", key_hex.encode()))
    short = _real(root, CV_AUDIT_LANE_KEY_FILE=_key_file(root / "s" / "j", key_hex[:63].encode()))
    reused = _real(root, CV_AUDIT_LANE_KEY_FILE=str(root / "s" / "k"), auth_pepper=key_hex)
    caplog.set_level(logging.DEBUG)

    with capture_logs() as logs:
        keys = load_lane_keys(good, environ={})
        refused = [
            _refusal(short, {}),
            _refusal(reused, {}),
            _refusal(good, {"CV_AUDIT_LANE_KEY_HEX": key_hex}),
        ]

    rendered = " ".join([*map(str, refused), *map(repr, refused), repr(logs), caplog.text])
    assert keys is not None
    assert keys.kid in repr(logs)
    leaks = (key_hex, key_hex.upper(), key_hex[:63], repr(keys.current))
    assert all(leak not in rendered for leak in leaks)
