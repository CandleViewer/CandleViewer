from candleviewer.settings import Settings

CONTENT = "must hold exactly 64 hex digits, optionally followed by one line feed"
OWNER = "must be mode 0400 and owned by the cv-api user"
UNDER = "must not lie under the directory of CV_AUDIT_WAL_PATH"
AUTH = ["auth_totp_key_hex", "auth_recovery_hmac_key_hex", "auth_csrf_key_hex"]
SECRETS = [*AUTH, "auth_csrf_previous_key_hex", "auth_pepper"]


@pytest.fixture
def key_hex() -> str:
    return secrets.token_hex(32)


@pytest.fixture
def fifo(tmp_path: Path) -> Iterator[Path]:
    """A FIFO with its writer end held open, so no open of it blocks whatever the flags (#2728's
    pattern): a regressed open fails the flags assertion instead of hanging the suite."""
    path = tmp_path.resolve() / "fifo"
    os.mkfifo(path, 0o600)
    writer = os.open(path, os.O_RDWR)
    yield path
    os.close(writer)


def _key_file(path: Path, content: bytes, mode: int = 0o400) -> str:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(content)
    path.chmod(mode)
    return str(path)


def _real(root: Path, **settings: Any) -> Settings:
    """A real audit backend whose WAL is under *root*; the key files go by their variables."""
    return Settings(
        storage_backend="real", audit_wal_path=str(root / "audit" / "a.wal"), **settings
    )


def _refusal(settings: Settings, environ: dict[str, str]) -> LaneKeyRefused:
    with pytest.raises(LaneKeyRefused) as refused:
        load_lane_keys(settings, environ=environ)
    return refused.value


def _record(monkeypatch: pytest.MonkeyPatch, module: object, name: str) -> list[tuple[Any, ...]]:
    """Every call of `module.<name>`, by its arguments; each still reaches the real function."""
    calls: list[tuple[Any, ...]] = []
    real = getattr(module, name)

    def _call(*args: Any) -> Any:
        calls.append(args)
        return real(*args)

    monkeypatch.setattr(module, name, _call)
    return calls


@pytest.mark.parametrize(
    ("case", "suffix"), [(str.lower, b"\n"), (str.upper, b"")], ids=["lower-lf", "upper"]
)
def test_a_key_file_of_64_hex_digits_reads_as_its_32_bytes(
    tmp_path: Path, key_hex: str, case: Callable[[str], str], suffix: bytes
) -> None:
    path = _key_file(tmp_path.resolve() / "k", case(key_hex).encode() + suffix)

    assert read_key_file(KEY_FILE, path) == bytes.fromhex(key_hex)


@pytest.mark.parametrize(
    "content",
    ["{k:.63}", "{k}0", "{k}\n\n", "{k}\r\n", "g{k:.63}", "", " {k}", "{k:.32}\n{k:.32}"],
    ids=["63-digits", "65-digits", "two-lf", "crlf", "non-hex", "empty", "space", "inner-lf"],
)
def test_a_key_file_with_any_other_content_is_refused(
    tmp_path: Path, key_hex: str, content: str
) -> None:
    path = _key_file(tmp_path.resolve() / "k", content.format(k=key_hex).encode())

    with pytest.raises(LaneKeyRefused, match=f"^{KEY_FILE} {CONTENT}$"):
        read_key_file(KEY_FILE, path)


@pytest.mark.parametrize(
    ("path", "rule"),
    [
        ("real/k", "must be an absolute path"),
        ("{root}/real/../real/k", "must not contain '..'"),
        ("{root}/link", "must not be a symlink"),
        ("{root}/linked/k", "must not be under a symlinked directory"),
    ],
    ids=["relative", "dot-dot", "symlink", "under-symlink"],
)
def test_the_loader_checks_the_path_like_the_test_clock_file(
    tmp_path: Path, key_hex: str, path: str, rule: str
) -> None:
    """The default path skips the load-time check, so the loader runs the same rules itself."""
    root = tmp_path.resolve()
    (root / "link").symlink_to(_key_file(root / "real" / "k", key_hex.encode()))
    (root / "linked").symlink_to(root / "real")

    with pytest.raises(LaneKeyRefused, match=f"^{PREVIOUS_KEY_FILE} {rule}$"):
        read_key_file(PREVIOUS_KEY_FILE, path.format(root=root))


def test_the_open_never_follows_a_symlink_swapped_in_after_the_path_check(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path, key_hex: str
) -> None:
    root = tmp_path.resolve()
    (root / "k").symlink_to(_key_file(root / "real", key_hex.encode()))
    monkeypatch.setattr(wiring, "key_file_path_refusal", lambda value: None)

    with pytest.raises(LaneKeyRefused, match=f"^{KEY_FILE} must not be a symlink$"):
        read_key_file(KEY_FILE, str(root / "k"))


@pytest.mark.parametrize("name", ["directory", "fifo"])
def test_a_key_path_that_is_no_regular_file_is_refused_without_blocking(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path, fifo: Path, name: str
) -> None:
    (tmp_path / "directory").mkdir()
    opened = _record(monkeypatch, os, "open")

    with pytest.raises(LaneKeyRefused, match=f"^{KEY_FILE} must name a regular file$"):
        read_key_file(KEY_FILE, str(tmp_path.resolve() / name))
    guards = os.O_NOFOLLOW | os.O_NONBLOCK
    assert [flags & guards for _, flags in opened] == [guards]


@pytest.mark.parametrize(
    ("call", "error"), [("open", PermissionError), ("fstat", OSError), ("read", OSError)]
)
def test_a_key_file_that_cannot_be_read_is_refused(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path, key_hex: str, call: str, error: type[OSError]
) -> None:
    path = _key_file(tmp_path.resolve() / "k", key_hex.encode())

    def _fail(*args: object) -> NoReturn:
        raise error("injected")

    monkeypatch.setattr(os, call, _fail)

    with pytest.raises(LaneKeyRefused, match=rf"^{KEY_FILE} cannot be read \({error.__name__}\)$"):
        read_key_file(KEY_FILE, path)


def test_the_loader_reads_at_most_66_bytes_of_a_key_file(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path, key_hex: str
) -> None:
    path = _key_file(tmp_path.resolve() / "k", key_hex.encode() * 64)
    reads = _record(monkeypatch, os, "read")

    with pytest.raises(LaneKeyRefused, match=f"^{KEY_FILE} {CONTENT}$"):
        read_key_file(KEY_FILE, path)
    assert sum(size for _, size in reads) == 66


@pytest.mark.parametrize("mode", [0o600, 0o440, 0o444, 0o640, 0o500])
def test_a_key_file_of_any_mode_but_0400_is_refused(
    tmp_path: Path, key_hex: str, mode: int
) -> None:
    path = _key_file(tmp_path.resolve() / "k", key_hex.encode(), mode)

    with pytest.raises(LaneKeyRefused, match=f"^{KEY_FILE} {OWNER}$"):
        read_key_file(KEY_FILE, path)


def test_a_key_file_owned_by_another_user_is_refused(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path, key_hex: str
) -> None:
    path = _key_file(tmp_path.resolve() / "k", key_hex.encode())
    monkeypatch.setattr(os, "geteuid", lambda: os.stat(path).st_uid + 1)

    with pytest.raises(LaneKeyRefused, match=f"^{KEY_FILE} {OWNER}$"):
        read_key_file(KEY_FILE, path)


