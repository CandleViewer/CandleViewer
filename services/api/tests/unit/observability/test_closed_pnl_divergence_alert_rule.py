"""#981 (E29-S06; the orchestrator's ruling Q5 of 2026-11-04): the `OmsClosedPnlDivergence`
ticket, which 20 Sec.12.1 lands with `oms_closed_pnl_divergence_total`.

`infra/prometheus/tests/system_alerts.test.yml` (promtool, run by CI; generated by
`infra/alertmanager/gen_promtool_tests.py`) proves when the rule fires and when it is silent. These
pins tie the rule to the comparison's counter, to Alertmanager's routes, the 07 section 9 entry and
the drill matrix, which promtool does not read. No PromQL is evaluated.
"""

from __future__ import annotations

from pathlib import Path

import yaml

from candleviewer.observability.metrics_catalogue import CATALOGUE
from candleviewer.oms.closed_pnl_compare import DIVERGENCE_TOTAL, WITHHELD_TOTAL
from tests.unit.observability.test_auth_backstop_alert_rules import (
    _route_for,
    _rule,
    _runbook_section,
)

_ROOT = Path(__file__).resolve().parents[5]
_PROMTOOL = _ROOT / "infra" / "prometheus" / "tests" / "system_alerts.test.yml"
_MATRIX = _ROOT / "qa" / "plans" / "e04-alert-drill-matrix.md"
_TICKET = "OmsClosedPnlDivergence"


def test_the_ticket_reads_a_sustained_non_zero_rate_of_the_unlabelled_counter() -> None:
    """20 Sec.12.1: a warning on a sustained non-zero rate; a lone record never holds 30 min."""
    rule = _rule(_TICKET)
    assert rule["expr"] == f"sum by (env) (rate({DIVERGENCE_TOTAL}[15m])) > 0"
    assert rule["for"] == "30m" and "keep_firing_for" not in rule
    spec = next(s for s in CATALOGUE if s.name == DIVERGENCE_TOTAL)
    assert (spec.kind, spec.labels, spec.max_series) == ("counter", (), 1)
    assert f"{_TICKET}:" in spec.alert and "(warning)" in spec.alert


def test_the_alert_is_an_oms_ticket_with_a_route() -> None:
    rule = _rule(_TICKET)
    assert rule["labels"] == {"severity": "ticket", "component": "oms"}
    anchor = "docs/plan/07-release-and-prr.md#alert-omsclosedpnldivergence"
    assert rule["annotations"]["runbook_url"] == anchor
    assert _route_for(rule["labels"])["receiver"]


def test_the_runbook_has_its_seven_elements_and_the_drill_matrix_its_row() -> None:
    section = _runbook_section(_rule(_TICKET))
    for element in (
        "1. What fired",
        "2. User impact",
        "3. What is still safe",
        "4. First three diagnostic commands",
        "5. Remediation",
        "6. Escalation",
        "7. Verify recovery",
    ):
        assert element in section, element
    for name in (DIVERGENCE_TOTAL, WITHHELD_TOTAL, "closed_pnl_venue_missing", "backpressure"):
        assert name in section, name
    rows = [
        line
        for line in _MATRIX.read_text(encoding="utf-8").splitlines()
        if line.startswith(f"| {_TICKET} |")
    ]
    assert len(rows) == 1 and "| ticket | 30m |" in rows[0]


def test_promtool_proves_a_sustained_rate_and_the_silences() -> None:
    cases = [
        case
        for test in yaml.safe_load(_PROMTOOL.read_text(encoding="utf-8"))["tests"]
        for case in test["alert_rule_test"]
        if case["alertname"] == _TICKET
    ]
    fired = sorted(case["eval_time"] for case in cases if case["exp_alerts"])
    silent = sorted(case["eval_time"] for case in cases if not case["exp_alerts"])
    assert fired == ["45m"] and silent == ["30m", "45m", "45m", "70m"]
