"""#914 (E29-T06 PR 1; the orchestrator's BQ-12 ruling): the `BybitRowsRefusedAccount` ticket.

`infra/prometheus/tests/system_alerts.test.yml` (promtool, run by CI; generated by
`infra/alertmanager/gen_promtool_tests.py`) proves when the rule fires and how long it is held.
These pins tie the rule to the counter the adapter declares and serves, to its one `reason`, to
Alertmanager's routes and inhibitions, the 07 section 9 entry and the drill matrix, which promtool
does not read. No PromQL is evaluated.
"""

from __future__ import annotations

import re
from pathlib import Path

import yaml

from candleviewer.exchange.bybit.trading_parse import owner_refusal
from candleviewer.ingestion.metrics import SPEC_BY_NAME
from tests.unit.observability.test_auth_backstop_alert_rules import (
    _alertmanager,
    _quiet_hours_minutes,
    _route_for,
    _rule,
    _runbook_section,
)

_ROOT = Path(__file__).resolve().parents[5]
_PROMTOOL = _ROOT / "infra" / "prometheus" / "tests" / "system_alerts.test.yml"
_MATRIX = _ROOT / "qa" / "plans" / "e04-alert-drill-matrix.md"
_TICKET = "BybitRowsRefusedAccount"
_SERIES = 'bybit_rows_refused_total{reason="account"}'


def test_the_ticket_reads_the_account_rows_a_rise_or_a_first_sample_in_the_hour() -> None:
    """A rise in the hour, or a first sample with none an hour before: the series is bound by its
    first refusal, so `increase` alone would miss the first row of each process."""
    rule = _rule(_TICKET)
    assert rule["expr"] == (
        f"sum by (env) (increase({_SERIES}[1h])) > 0 "
        f"or (sum by (env) ({_SERIES}) > 0 "
        f"unless sum by (env) ({_SERIES} offset 1h))"
    )
    assert rule["for"] == "0m"
    assert re.findall(r'reason="(\w+)"', rule["expr"]) == ["account"] * 3


def test_the_counter_is_the_adapters_and_account_is_one_of_its_reasons() -> None:
    """The series the rule reads is the adapter's own counter of trading-read rows set aside
    (24 Sec.14.2 rule 12), with `reason` its one label and `account` one of its values."""
    spec = SPEC_BY_NAME["bybit_rows_refused_total"]
    assert (spec.kind, spec.labels, spec.owner) == ("counter", ("reason",), "adapter")
    assert "account" in str(owner_refusal.__annotations__["return"])


def test_the_alert_is_a_ticket_of_the_secrets_component_never_inhibited_by_postgres() -> None:
    """A cross-account row is a key and an account mixed up (C-2.11): a credential signal, which
    stays visible during a database outage (SR-125)."""
    rule = _rule(_TICKET)
    assert rule["labels"] == {"severity": "ticket", "component": "secrets"}
    assert rule["annotations"]["runbook_url"] == (
        "docs/plan/07-release-and-prr.md#alert-bybitrowsrefusedaccount"
    )
    [postgres] = [
        r for r in _alertmanager()["inhibit_rules"]
        if r["source_matchers"] == ['alertname = "PostgresDown"']
    ]  # fmt: skip
    [pattern] = [
        m.split("=~", 1)[1].strip().strip('"')
        for m in postgres["target_matchers"]
        if m.startswith("component")
    ]
    assert re.fullmatch(pattern, "oms") and re.fullmatch(pattern, "secrets") is None
    assert _route_for({"severity": "ticket", "component": "secrets"})["receiver"]


def test_the_ticket_is_held_firing_for_longer_than_the_quiet_hours_mute() -> None:
    hold = re.fullmatch(r"(\d+)h(\d+)m", _rule(_TICKET)["keep_firing_for"])
    assert hold and int(hold[1]) * 60 + int(hold[2]) > _quiet_hours_minutes() >= 9 * 60


def test_the_runbook_has_its_seven_elements_and_the_drill_matrix_its_row() -> None:
    section = _runbook_section(_rule(_TICKET))
    for element in (
        "1. What fired",
        "2. User impact",
        "3. What is still safe",
        "5. Remediation",
        "6. Escalation",
        "7. Verify recovery",
        "4. First three diagnostic commands",
    ):
        assert element in section, element  # fmt: skip
    assert "bybit_rows_refused_total" in section and "C-2.11" in section
    rows = [
        line
        for line in _MATRIX.read_text(encoding="utf-8").splitlines()
        if line.startswith(f"| {_TICKET} |")
    ]
    assert len(rows) == 1 and "| ticket | 0m |" in rows[0]


def test_promtool_proves_a_rise_a_first_sample_the_hold_and_the_silences() -> None:
    cases = [
        case
        for test in yaml.safe_load(_PROMTOOL.read_text(encoding="utf-8"))["tests"]
        for case in test["alert_rule_test"]
        if case["alertname"] == _TICKET
    ]
    fired = sorted(case["eval_time"] for case in cases if case["exp_alerts"])
    silent = sorted(case["eval_time"] for case in cases if not case["exp_alerts"])
    assert fired == ["10h", "6m", "6m"] and silent == ["11h", "11h", "6m"]
