"""#981 (E29-S06; the orchestrator's review of 2026-11-04): the `OmsClosedPnlAccountCrossing`
ticket, modelled on `BybitRowsRefusedAccount` and pinned as its rule is.

`infra/prometheus/tests/system_alerts.test.yml` (promtool, run by CI; generated by
`infra/alertmanager/gen_promtool_tests.py`) proves when the rule fires and how long it is held.
These pins tie the rule to the closed-PnL sync's histogram and its `other_account` result, to
Alertmanager's routes and inhibitions, the 07 section 9 entry and the drill matrix, which promtool
does not read. No PromQL is evaluated.
"""

from __future__ import annotations

import re
from pathlib import Path

import yaml

from candleviewer.observability.metrics_catalogue import CATALOGUE
from candleviewer.oms.closed_pnl_sync import FETCH_RESULTS, FETCH_SECONDS
from tests.unit.observability.test_auth_backstop_alert_rules import (
    _alertmanager,
    _quiet_hours_minutes,
    _route_for,
    _rule,
    _runbook_section,
)

_ROOT = Path(__file__).resolve().parents[5]
_PROMTOOL = _ROOT / "infra" / "prometheus" / "tests" / "system_alerts.test.yml"
_MATRIX = _ROOT / "qa" / "plans" / "e04-alert-drill-matrix.md"
_TICKET, _MODEL = "OmsClosedPnlAccountCrossing", "BybitRowsRefusedAccount"
_SERIES = f'{FETCH_SECONDS}_count{{result="other_account"}}'


def test_the_ticket_reads_the_crossings_a_rise_or_a_first_sample_in_the_hour() -> None:
    """As its model's: the `other_account` child is bound by the first crossing, so `increase`
    alone would miss the first of each process."""
    rule = _rule(_TICKET)
    assert rule["expr"] == (
        f"sum by (env) (increase({_SERIES}[1h])) > 0 "
        f"or (sum by (env) ({_SERIES}) > 0 "
        f"unless sum by (env) ({_SERIES} offset 1h))"
    )
    assert (rule["for"], rule["keep_firing_for"]) == ("0m", _rule(_MODEL)["keep_firing_for"])
    hold = re.fullmatch(r"(\d+)h(\d+)m", rule["keep_firing_for"])
    assert hold and int(hold[1]) * 60 + int(hold[2]) > _quiet_hours_minutes() >= 9 * 60


def test_the_series_is_the_syncs_histogram_with_the_crossing_one_of_its_results() -> None:
    spec = next(s for s in CATALOGUE if s.name == FETCH_SECONDS)
    assert (spec.kind, spec.labels, spec.max_series) == ("histogram", ("result",), 3)
    assert FETCH_RESULTS == ("ok", "failed", "other_account")
    assert set(FETCH_RESULTS) <= set(re.findall(r"\w+", spec.help))
    assert f"{_TICKET}: other_account" in spec.alert and "(ticket" in spec.alert


def test_the_alert_is_a_ticket_of_the_secrets_component_never_inhibited_by_postgres() -> None:
    """A crossing between accounts is an isolation signal (C-2.11), visible during a database
    outage as its model is (SR-125)."""
    rule = _rule(_TICKET)
    labels = {"severity": "ticket", "component": "secrets"}
    assert rule["labels"] == _rule(_MODEL)["labels"] == labels
    anchor = "docs/plan/07-release-and-prr.md#alert-omsclosedpnlaccountcrossing"
    assert rule["annotations"]["runbook_url"] == anchor
    [postgres] = [
        r for r in _alertmanager()["inhibit_rules"]
        if r["source_matchers"] == ['alertname = "PostgresDown"']
    ]  # fmt: skip
    [pattern] = [
        m.split("=~", 1)[1].strip().strip('"')
        for m in postgres["target_matchers"]
        if m.startswith("component")
    ]
    assert re.fullmatch(pattern, "secrets") is None
    assert _route_for(rule["labels"])["receiver"]


def test_the_runbook_has_its_seven_elements_and_the_drill_matrix_its_row() -> None:
    section = _runbook_section(_rule(_TICKET))
    for element in (
        "1. What fired",
        "2. User impact",
        "3. What is still safe",
        "4. First three diagnostic commands",
        "5. Remediation",
        "6. Escalation",
        "7. Verify recovery",
    ):
        assert element in section, element
    assert FETCH_SECONDS in section and "C-2.11" in section and "_OtherAccount" in section
    rows = [
        line
        for line in _MATRIX.read_text(encoding="utf-8").splitlines()
        if line.startswith(f"| {_TICKET} |")
    ]
    assert len(rows) == 1 and "| ticket | 0m |" in rows[0]


def test_promtool_proves_a_rise_a_first_sample_the_hold_and_the_silences() -> None:
    cases = [
        case
        for test in yaml.safe_load(_PROMTOOL.read_text(encoding="utf-8"))["tests"]
        for case in test["alert_rule_test"]
        if case["alertname"] == _TICKET
    ]
    fired = sorted(case["eval_time"] for case in cases if case["exp_alerts"])
    silent = sorted(case["eval_time"] for case in cases if not case["exp_alerts"])
    assert fired == ["10h", "6m", "6m"] and silent == ["11h", "11h", "6m"]
