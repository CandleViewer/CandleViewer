"""SR-028 password policy (#2330, #2110; `04-security-program.md` Sec.6.3.1): the one module a
password change and invite redemption share (BQ-234).

The rules, in the order they are checked: at least `MIN_LENGTH` code points (`24` `AuthConfig.
password_min_length`, ruled on #2330) and at most `MAX_LENGTH`; not on the local breached-password
list and not fewer than 4 distinct characters (`password_breached`); not containing the username
or the email's local part of 3 characters or more (`password_policy`). Lengths are counted in code
points, as Python's `len` counts a `str`.

The breached-password list is offline (SR-028 "local"; no HIBP, no k-anonymity call: C-12.9,
C-13.5): SHA-1 hex digests, one per line, of passwords normalised to NFC and lower-cased, read
once from `data/breached_passwords.sha1` (generated by `scripts/build_breached_passwords.py`).
A digest list keeps the file unreadable and secret scanners quiet; SHA-1 is a lookup key here,
never a password hash.
"""

from __future__ import annotations

import hashlib
import unicodedata
from dataclasses import dataclass
from enum import StrEnum
from functools import cache
from pathlib import Path
from typing import Final

#: `24-internal-schemas.md` `AuthConfig.password_min_length` (#2330 ruling: `24`'s 14 stands).
MIN_LENGTH: Final = 14
MAX_LENGTH: Final = 512
#: The shortest identity part (username, email local part) the containment rule looks for.
MIN_IDENTITY_PART: Final = 3
#: Fewer distinct characters than this is a simple pattern (`password_breached`).
MIN_DISTINCT: Final = 4
BREACHED_LIST_PATH: Final = Path(__file__).resolve().parent / "data" / "breached_passwords.sha1"


class PolicyCode(StrEnum):
    """The `code` of a refusal (`22` `x-error-codes`)."""

    BREACHED = "password_breached"
    POLICY = "password_policy"


class PolicyRule(StrEnum):
    """`errors[].rule` of a `password_policy` refusal; `breached` names the list rule."""

    MIN_LENGTH = "min_length"
    MAX_LENGTH = "max_length"
    CONTAINS_IDENTITY = "contains_identity"
    BREACHED = "breached"
    SIMPLE_PATTERN = "simple_pattern"


#: `04` Sec.6.3.1: the `detail` of each refusal (D05's W-strings; design owns the copy).
DETAILS: Final[dict[PolicyRule, str]] = {
    PolicyRule.MIN_LENGTH: f"Use at least {MIN_LENGTH} characters.",
    PolicyRule.MAX_LENGTH: f"Use at most {MAX_LENGTH} characters.",
    PolicyRule.CONTAINS_IDENTITY: "Your password can't contain your username or email.",
    PolicyRule.BREACHED: "This password appears in a known breach list.",
    PolicyRule.SIMPLE_PATTERN: "This password appears in a known breach list.",
}


@dataclass(frozen=True, slots=True)
class PolicyVerdict:
    """A refusal: its `code`, the rule that refused and the user-safe `detail`. Never the value."""

    code: PolicyCode
    rule: PolicyRule

    @property
    def detail(self) -> str:
        return DETAILS[self.rule]


def normalise(password: str) -> str:
    """The form the breached list is keyed by: NFC, then lower-cased."""
    return unicodedata.normalize("NFC", password).lower()


def digest(password: str) -> str:
    """The list key of *password*: SHA-1 hex of its normalised UTF-8 bytes (a lookup key only)."""
    return hashlib.sha1(normalise(password).encode("utf-8"), usedforsecurity=False).hexdigest()


def parse_breached_list(text: str) -> frozenset[str]:
    """The digests of a list file: one lower-case 40-hex digest per line; `#` lines are comments.
    A malformed line is refused (`ValueError`), so a damaged file fails at start, never silently."""
    digests: set[str] = set()
    for number, raw in enumerate(text.splitlines(), start=1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if len(line) != 40 or line.strip("0123456789abcdef"):
            raise ValueError(f"breached-password list line {number} is not a SHA-1 hex digest")
        digests.add(line)
    return frozenset(digests)


@cache
def breached_list(path: Path = BREACHED_LIST_PATH) -> frozenset[str]:
    """The list, read once per process (it never changes while the process runs)."""
    return parse_breached_list(path.read_text(encoding="utf-8"))


def check(
    password: str,
    *,
    username: str,
    email: str,
    breached: frozenset[str] | None = None,
) -> PolicyVerdict | None:
    """The first rule *password* breaks, or `None` when it passes them all."""
    if len(password) < MIN_LENGTH:
        return PolicyVerdict(PolicyCode.POLICY, PolicyRule.MIN_LENGTH)
    if len(password) > MAX_LENGTH:
        return PolicyVerdict(PolicyCode.POLICY, PolicyRule.MAX_LENGTH)
    listed = breached_list() if breached is None else breached
    if digest(password) in listed:
        return PolicyVerdict(PolicyCode.BREACHED, PolicyRule.BREACHED)
    lowered = normalise(password)
    if len(set(lowered)) < MIN_DISTINCT:
        return PolicyVerdict(PolicyCode.BREACHED, PolicyRule.SIMPLE_PATTERN)
    parts = (normalise(username), normalise(email.split("@", 1)[0]))  # as the password is
    if any(len(part) >= MIN_IDENTITY_PART and part in lowered for part in parts):
        return PolicyVerdict(PolicyCode.POLICY, PolicyRule.CONTAINS_IDENTITY)
    return None
