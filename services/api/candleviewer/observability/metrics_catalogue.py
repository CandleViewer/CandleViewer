@dataclass(frozen=True, slots=True)
class MetricSpec:
    name: str
    kind: MetricKind
    unit: str
    labels: tuple[str, ...]
    help: str
    alert: str
    status: Status
    owner_epic: str
    buckets: tuple[float, ...] | None = None
    max_series: int = 200
    #: Live, but created at module level by its owner and served by a `ReexportCollector`
    #: (e.g. `bars.metrics.export_bars_metrics`); `register_r0()` must not register it twice.
    exported: bool = False


def _s(
    name: str,
    kind: MetricKind,
    unit: str,
    labels: tuple[str, ...],
    help_text: str,
    alert: str,
    status: Status,
    owner: str,
    buckets: tuple[float, ...] | None = None,
    max_series: int = 200,
    exported: bool = False,
) -> MetricSpec:
    return MetricSpec(
        name, kind, unit, labels, help_text, alert, status, owner, buckets, max_series, exported
    )


